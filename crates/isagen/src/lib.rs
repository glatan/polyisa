//! ISADL からのコード生成。検査済みモデルを受け、Rust の源を文字列で返す。
//!
//! 詳しくは [ISA 記述言語](../../../docs/design/isa-description.md) の「生成物」を見る。
//! この骨格は線形のデコーダと単純な逆アセンブラを生成する。
//! 決定木への最適化と `build.rs` への組み込みは後の段階で足す。

#![forbid(unsafe_code)]

pub use polyisa_isadl::Model;

/// 生成に失敗した理由。
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum GenError {
    Invalid(Vec<polyisa_isadl::ValidationError>),
    /// デコーダが評価できない `when` の機能旗。128 個を超える旗で
    /// 符号化を区別しようとしたときに使う。
    UnsupportedWhen(String),
    /// 検査を通っていないモデルに対する生成要求（vex+evex の同居など）。
    Custom(String),
}

impl core::fmt::Display for GenError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Invalid(es) => write!(f, "invalid model ({} errors)", es.len()),
            Self::UnsupportedWhen(name) => write!(f, "unsupported when flag: {name}"),
            Self::Custom(msg) => write!(f, "{msg}"),
        }
    }
}

/// 検査して生成する。検査の違反があれば生成しない。
pub fn generate(model: &Model) -> Result<Generated, GenError> {
    let report = polyisa_isadl::validate(model);
    if !report.errors.is_empty() {
        return Err(GenError::Invalid(report.errors));
    }
    Ok(Generated {
        insn_type: gen_insn_type(model),
        decoder: gen_decoder(model)?,
        disassembler: gen_disassembler(model),
        encoder: gen_encoder(model)?,
        operands: gen_operands(model),
        metadata: gen_metadata(model),
        map_decoder: gen_map_decoder(model)?,
    })
}

/// 生成物の束。
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Generated {
    pub insn_type: String,
    pub decoder: String,
    pub disassembler: String,
    pub encoder: String,
    pub operands: String,
    pub metadata: String,
    /// オペコード表（`map`）を持つモデル用の、バイト列からのデコーダ。
    /// 表を持たないモデルでは空文字列。
    pub map_decoder: String,
}

/// `map` 内の命令項目を名前順・重複なしで集める。同一命令が複数の
/// オペコード値に並ぶ（+r 系）ため、名前でまとめる。
fn map_insns(model: &Model) -> Vec<&polyisa_isadl::model::MapInsn> {
    let mut seen = std::collections::BTreeSet::new();
    let mut out = Vec::new();
    for map in &model.maps {
        for item in &map.items {
            if let polyisa_isadl::model::MapItem::Insn(_, mi) = item
                && seen.insert(mi.name.as_str())
            {
                out.push(mi);
            }
        }
    }
    out
}

fn gen_insn_type(model: &Model) -> String {
    let mut s = String::from("// generated by isagen. do not edit.\n");
    s.push_str("#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]\n");
    s.push_str("pub enum Insn {\n");
    if model.insns.is_empty() {
        s.push_str("    #[default]\n    Bad,\n");
    }
    for (k, insn) in model.insns.iter().enumerate() {
        if k == 0 {
            s.push_str("    #[default]\n");
        }
        s.push_str(&format!("    {},\n", to_ident(&insn.name)));
    }
    for mi in map_insns(model) {
        s.push_str(&format!("    {},\n", to_ident(&mi.name)));
    }
    s.push_str("}\n");
    s
}

fn gen_decoder(model: &Model) -> Result<String, GenError> {
    let mut s = String::from("// generated by isagen: linear decoder.\n");
    s.push_str("pub fn decode(word: u128, len: u32) -> Option<Insn> {\n");
    s.push_str("    decode_model(word, len, true)\n");
    s.push_str("}\n");
    // モデル対応デコード（ADR-0006）。`when` の述語を評価し、符号化の
    // 重なりを機能で解決する。XLEN（rv32/rv64）は `is_rv64` で受け、
    // それ以外の機能旗は `feats` のビット集合で受ける。
    // `decode` と `decode_model` は既定 CPU モデルの機能集合（`DEFAULT_FEATS`）
    // を選ぶ互換用の殻である。
    s.push_str("pub fn decode_model(word: u128, len: u32, is_rv64: bool) -> Option<Insn> {\n");
    s.push_str("    decode_model_ex(word, len, is_rv64, DEFAULT_FEATS)\n");
    s.push_str("}\n");
    let extra = extra_flags(model)?;
    for (i, name) in extra.iter().enumerate() {
        s.push_str(&format!(
            "pub const {}: u128 = 1u128 << {};\n",
            feat_const(name),
            i
        ));
    }
    // 機能名から feats のビットへの対応。CPU モデルの解決が使う。
    s.push_str("pub const FEAT_BITS: &[(&str, u128)] = &[\n");
    for name in &extra {
        s.push_str(&format!("    ({name:?}, {}),\n", feat_const(name)));
    }
    s.push_str("];\n");
    s.push_str(
        "pub fn decode_model_ex(word: u128, len: u32, is_rv64: bool, feats: u128) -> Option<Insn> {\n",
    );
    // `when` を使わないモデルでは `is_rv64` と `feats` が未使用になる。
    // 呼び出し側の互換性のため引数は残し、警告が出ないよう明示的に破棄する。
    // ビット番号は辞書順で決まるため、新しい旗の追加でずれる。
    // 呼び出し側は数値を直書きせず、生成した `FEAT_*` 定数を使うこと。
    let uses_is_rv64 = model.insns.iter().any(|i| {
        when_guard(&i.when, &extra)
            .unwrap_or_default()
            .contains("is_rv64")
    });
    if !uses_is_rv64 {
        s.push_str("    let _ = is_rv64;\n");
    }
    let uses_feats = model.insns.iter().any(|i| {
        when_guard(&i.when, &extra)
            .unwrap_or_default()
            .contains("feats")
    });
    if !uses_feats {
        s.push_str("    let _ = feats;\n");
    }
    s.push_str("    match len {\n");
    // 長さごとに分岐する。RISC-V C拡張の16ビット命令と32ビット命令の混在を想定する。
    let mut lens: Vec<u32> = model.insns.iter().map(|i| i.pattern.len()).collect();
    lens.sort_unstable();
    lens.dedup();
    for l in lens {
        s.push_str(&format!("        {l} => {{\n"));
        for insn in model.insns.iter().filter(|i| i.pattern.len() == l) {
            let guard = when_guard(&insn.when, &extra)?;
            let check = if guard.is_empty() {
                format!(
                    "word & {:#x} == {:#x}",
                    insn.pattern.mask(),
                    insn.pattern.bits()
                )
            } else {
                format!(
                    "word & {:#x} == {:#x} && ({guard})",
                    insn.pattern.mask(),
                    insn.pattern.bits()
                )
            };
            s.push_str(&format!(
                "            // {} (mask {:#x}, bits {:#x})\n",
                insn.name,
                insn.pattern.mask(),
                insn.pattern.bits()
            ));
            if insn.wheres.is_empty() {
                s.push_str(&format!(
                    "            if {check} {{\n                return Some(Insn::{});\n            }}\n",
                    to_ident(&insn.name)
                ));
                continue;
            }
            // `where` 付き：一致後にフィールド値を取り出して条件を評価する。
            s.push_str(&format!("            if {check} {{\n"));
            let tag = to_snake(&insn.name);
            let (decls, conds) = where_decls_conds(model, insn, &tag);
            for d in &decls {
                s.push_str(&format!("                {d}\n"));
            }
            s.push_str(&format!(
                "                if {} {{\n                    return Some(Insn::{});\n                }}\n            }}\n",
                conds.join(" && "),
                to_ident(&insn.name)
            ));
        }
        s.push_str("            None\n        }\n");
    }
    s.push_str("        _ => None,\n    }\n}\n");
    Ok(s)
}

/// `when` 述語をデコーダ入口の引数に対する Rust 式にする。
/// 空文字は無条件（`Pred::True`）を表す。XLEN（rv32/rv64）は `is_rv64`
/// で受け、それ以外の機能旗は `feats` のビット集合で受ける。
/// ビットの割り当ては `extra_flags` が決める。
fn when_guard(pred: &polyisa_isadl::pred::Pred, extra: &[String]) -> Result<String, GenError> {
    use polyisa_isadl::pred::Pred;
    match pred {
        Pred::True => Ok(String::new()),
        Pred::False => Ok("false".to_string()),
        Pred::Flag(name) if name == "rv64" => Ok("is_rv64".to_string()),
        Pred::Flag(name) if name == "rv32" => Ok("!is_rv64".to_string()),
        // 呼び出し側が括弧で囲むため、ここでは付けない。
        Pred::Flag(name) if extra.iter().any(|f| f == name) => {
            Ok(format!("feats & {} != 0", feat_const(name)))
        }
        Pred::Flag(name) => Err(GenError::UnsupportedWhen(name.clone())),
        Pred::Not(inner) => Ok(format!("!({})", when_guard(inner, extra)?)),
        Pred::All(ps) => {
            let mut parts = Vec::new();
            for p in ps {
                parts.push(format!("({})", when_guard(p, extra)?));
            }
            Ok(parts.join(" && "))
        }
        Pred::Any(ps) => {
            let mut parts = Vec::new();
            for p in ps {
                parts.push(format!("({})", when_guard(p, extra)?));
            }
            Ok(parts.join(" || "))
        }
    }
}

/// `when` に現れる XLEN 以外の機能旗を集める。辞書順に並べ、位置が
/// ビット番号になる。64 個を超えたら生成しない。実行モードの旗
/// （`m64`、`opd_o16` 等）は `modes` 側で解決するので除く。
fn extra_flags(model: &Model) -> Result<Vec<String>, GenError> {
    use polyisa_isadl::model::ModeType;
    use polyisa_isadl::pred::Pred;
    let mut mode_names: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for m in &model.modes {
        match &m.ty {
            ModeType::Bool => {
                mode_names.insert(m.name.clone());
            }
            ModeType::Enum(vars) => {
                for v in vars {
                    mode_names.insert(format!("{}_{}", m.name, v));
                }
            }
        }
    }
    fn collect(pred: &Pred, out: &mut Vec<String>) {
        match pred {
            Pred::True | Pred::False => {}
            Pred::Flag(name) => {
                if name != "rv32" && name != "rv64" && !out.iter().any(|f| f == name) {
                    out.push(name.clone());
                }
            }
            Pred::Not(inner) => collect(inner, out),
            Pred::All(ps) | Pred::Any(ps) => {
                for p in ps {
                    collect(p, out);
                }
            }
        }
    }
    let mut out = Vec::new();
    for insn in &model.insns {
        collect(&insn.when, &mut out);
    }
    for map in &model.maps {
        for item in &map.items {
            if let polyisa_isadl::model::MapItem::Insn(_, mi) = item {
                collect(&mi.when, &mut out);
            }
        }
    }
    // `when` で参照されなくても、CPU モデル宣言が使う機能は旗を持つ。
    // `model_feats` の解決と実行時の世代判定に FEAT_* 定数が必要。
    for m in &model.models {
        for f in m.add_features.iter().chain(m.remove_features.iter()) {
            if !mode_names.contains(f) && !out.iter().any(|x| x == f) {
                out.push(f.clone());
            }
        }
    }
    // モデル宣言が辿る implies 先の機能も旗が要る。
    loop {
        let mut grew = false;
        for f in &model.features {
            if out.iter().any(|x| x == &f.name) {
                for i in &f.implies {
                    if !mode_names.contains(i) && !out.iter().any(|x| x == i) {
                        out.push(i.clone());
                        grew = true;
                    }
                }
            }
        }
        if !grew {
            break;
        }
    }
    out.retain(|f| !mode_names.contains(f));
    out.sort();
    {
        use std::collections::BTreeSet;
        let mut seen = BTreeSet::new();
        for f in &out {
            if !seen.insert(feat_const(f)) {
                return Err(GenError::UnsupportedWhen(format!(
                    "conflicting feature flag names for {f}"
                )));
            }
        }
    }
    if out.len() > 128 {
        return Err(GenError::UnsupportedWhen(format!(
            "too many feature flags: {}",
            out.len()
        )));
    }
    Ok(out)
}

/// 機能旗の名前を生成コードの定数名にする。
fn feat_const(name: &str) -> String {
    let mut s = String::from("FEAT_");
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            s.push(c.to_ascii_uppercase());
        } else {
            s.push('_');
        }
    }
    s
}

fn gen_disassembler(model: &Model) -> String {
    let mut s = String::from("// generated by isagen: disassembler.\n");
    s.push_str("pub fn disasm(insn: Insn) -> &'static str {\n    match insn {\n");
    for insn in &model.insns {
        s.push_str(&format!(
            "        Insn::{} => {:?},\n",
            to_ident(&insn.name),
            insn.syntax
        ));
    }
    for mi in map_insns(model) {
        s.push_str(&format!(
            "        Insn::{} => {:?},\n",
            to_ident(&mi.name),
            mi.syntax
        ));
    }
    s.push_str("    }\n}\n");
    // 語をデコードし、構文の {名} をオペランド値で埋める。オペランド値は
    // `extract_ops` と同じ規則（レジスタは接頭辞つき、即値は 10 進）。
    // 埋められない穴（未宣言のプレースホルダ）はそのまま残す。
    s.push_str(
        "pub fn disasm_word(word: u128, len: u32) -> Option<String> {\n    \
            let insn = decode(word, len)?;\n    render_ops(insn, word)\n}\n",
    );
    s.push_str("fn render_ops(insn: Insn, word: u128) -> Option<String> {\n");
    let formats: std::collections::BTreeMap<&str, &polyisa_isadl::model::Format> =
        model.formats.iter().map(|f| (f.name.as_str(), f)).collect();
    let fields: std::collections::BTreeMap<&str, &polyisa_isadl::model::Field> =
        model.fields.iter().map(|f| (f.name.as_str(), f)).collect();
    let regprefix = |op: &polyisa_isadl::model::Operand| -> Option<&str> {
        op.regclass.as_deref().and_then(|c| {
            model
                .regclasses
                .iter()
                .find(|r| r.name == c)
                .and_then(|r| r.prefix.as_deref())
        })
    };
    let mut arms = Vec::new();
    let mut missing = !map_insns(model).is_empty();
    for insn in &model.insns {
        let fmt = formats[insn.format.as_str()];
        // Hook フィールドを持つオペランドが形式に1つでもあれば
        // `extract_ops` がアームを出さない（空 vec を返す）ので、
        // render_ops 側も同じ条件でアームを出さない。
        let hook = fmt.operands.iter().any(|op| {
            matches!(
                fields[op.field.as_deref().unwrap_or(op.name.as_str())].kind,
                polyisa_isadl::model::FieldKind::Hook { .. }
            )
        });
        if hook {
            missing = true;
            continue;
        }
        // 構文中の穴を埋める置き換えだけを出す。
        let mut replaces = Vec::new();
        for (i, op) in fmt.operands.iter().enumerate() {
            let ph = format!("{{{}}}", op.name);
            if !insn.syntax.contains(&ph) {
                continue;
            }
            let val = match regprefix(op) {
                Some(p) => format!("format!(\"{{}}{{}}\", {p:?}, o[{i}])"),
                None => format!("o[{i}].to_string()"),
            };
            replaces.push(format!("s = s.replace({ph:?}, &{val});"));
        }
        let mut arm = format!("        Insn::{} => {{\n", to_ident(&insn.name));
        if replaces.is_empty() {
            arm.push_str(&format!(
                "            Some({:?}.to_string())\n",
                insn.syntax
            ));
        } else {
            arm.push_str("            let o = extract_ops(insn, word);\n");
            arm.push_str(&format!(
                "            let mut s = {:?}.to_string();\n",
                insn.syntax
            ));
            for r in replaces {
                arm.push_str(&format!("            {r}\n"));
            }
            arm.push_str("            Some(s)\n");
        }
        arm.push_str("        }\n");
        arms.push(arm);
    }
    if !arms.iter().any(|a| a.contains("extract_ops")) {
        s.push_str("    let _ = word;\n");
    }
    s.push_str("    match insn {\n");
    for a in arms {
        s.push_str(&a);
    }
    if missing {
        s.push_str("        _ => Some(disasm(insn).to_string()),\n");
    }
    s.push_str("    }\n}\n");
    s
}

/// `where` の条件を評価するための、フィールドの取り出しと比較式の生成。
/// 戻り値は (let 文の並び, 比較式の並び)。フィールドは `Bits` だけが
/// 来る（検査で他の種別は拒否される）。
fn where_decls_conds(
    model: &Model,
    insn: &polyisa_isadl::model::Insn,
    tag: &str,
) -> (Vec<String>, Vec<String>) {
    let mut decls = Vec::new();
    let mut conds = Vec::new();
    let bits_of = |name: &str| match model.fields.iter().find(|f| f.name == name) {
        Some(f) => match f.kind {
            polyisa_isadl::model::FieldKind::Bits { hi, lo } => (hi, lo),
            _ => (0, 0),
        },
        None => (0, 0),
    };
    for (k, w) in insn.wheres.iter().enumerate() {
        let (hi, lo) = bits_of(&w.field);
        let width = hi - lo + 1;
        let mask: u128 = if width >= 128 {
            u128::MAX
        } else {
            (1u128 << width) - 1
        };
        if lo == 0 {
            decls.push(format!("let w_{tag}_{k} = word & {mask:#x};"));
        } else {
            decls.push(format!("let w_{tag}_{k} = (word >> {lo}) & {mask:#x};"));
        }
        let op = match w.op {
            polyisa_isadl::model::WhereOp::Eq => "==",
            polyisa_isadl::model::WhereOp::Ne => "!=",
            polyisa_isadl::model::WhereOp::Lt => "<",
            polyisa_isadl::model::WhereOp::Le => "<=",
            polyisa_isadl::model::WhereOp::Gt => ">",
            polyisa_isadl::model::WhereOp::Ge => ">=",
        };
        match &w.rhs {
            polyisa_isadl::model::WhereRhs::Lit(value) => {
                conds.push(format!("w_{tag}_{k} {op} {value:#x}"));
            }
            polyisa_isadl::model::WhereRhs::Field(name) => {
                let (hi2, lo2) = bits_of(name);
                let width2 = hi2 - lo2 + 1;
                let mask2: u128 = if width2 >= 128 {
                    u128::MAX
                } else {
                    (1u128 << width2) - 1
                };
                if lo2 == 0 {
                    decls.push(format!("let w2_{tag}_{k} = word & {mask2:#x};"));
                } else {
                    decls.push(format!("let w2_{tag}_{k} = (word >> {lo2}) & {mask2:#x};"));
                }
                conds.push(format!("w_{tag}_{k} {op} w2_{tag}_{k}"));
            }
        }
    }
    (decls, conds)
}

/// `Parts` フィールドの論理値を命令語に散らすコードと、読み戻して
/// 論理値を組み立てる式を生成する。`parts` は上位側から並ぶ。
fn parts_scatter(parts: &[(u32, u32)], v: &str, word: &str, len: u32) -> String {
    let total: u32 = parts.iter().map(|(hi, lo)| hi - lo + 1).sum();
    let mut shift = total;
    let mut out = String::new();
    for (hi, lo) in parts {
        let w = hi - lo + 1;
        shift -= w;
        // 語の中に収まる分だけを書く。語外の論理ビットは読み戻しの
        // 一致検査が 0 を要求する。
        let inw = len.saturating_sub(*lo).min(w);
        if inw == 0 {
            continue;
        }
        let mask: u64 = if inw >= 64 {
            u64::MAX
        } else {
            (1u64 << inw) - 1
        };
        let take = if shift == 0 {
            format!("({v} & {mask:#x})")
        } else {
            format!("(({v} >> {shift}) & {mask:#x})")
        };
        if *lo == 0 {
            out.push_str(&format!("    {word} |= {take} as u128;\n"));
        } else {
            out.push_str(&format!("    {word} |= ({take} as u128) << {lo};\n"));
        }
    }
    out
}

fn parts_gather(parts: &[(u32, u32)], word: &str, dst_ty: &str, len: u32) -> String {
    // 部 i の論理値上のシフト量は、後続の部の幅の和。語長を越える
    // 分は取れず、その位置は 0 になる（呼び出し側の一致検査で
    // 論理値の語外ビットに 0 を要求する形になる）。
    let mut expr = String::new();
    let mut first = true;
    for (i, (hi, lo)) in parts.iter().enumerate() {
        let w = hi - lo + 1;
        let inw = len.saturating_sub(*lo).min(w);
        if inw == 0 {
            continue;
        }
        let mask: u128 = if inw >= 128 {
            u128::MAX
        } else {
            (1u128 << inw) - 1
        };
        let get = if *lo == 0 {
            format!("({word} & {mask:#x})")
        } else {
            format!("(({word} >> {lo}) & {mask:#x})")
        };
        let shift: u32 = parts[i + 1..].iter().map(|(h, l)| h - l + 1).sum();
        if !first {
            expr.push_str(" | ");
        }
        first = false;
        if shift == 0 {
            expr.push_str(&format!("({get} as {dst_ty})"));
        } else {
            expr.push_str(&format!("(({get} as {dst_ty}) << {shift})"));
        }
    }
    if expr.is_empty() {
        expr.push('0');
    }
    expr
}

/// `when` 述語を満たす `(is_rv64, feats)` を一つ見つける。見つからなければ
/// `None`（`Pred::False` など）。実空間は `is_rv64` 一変数と `feats` の
/// 集合で、`flag("rv64") = is_rv64`、`flag("rv32") = !is_rv64` と評価する。
fn satisfy_when(
    pred: &polyisa_isadl::pred::Pred,
    extra: &[String],
    features: &[polyisa_isadl::model::Feature],
) -> Option<(bool, u128)> {
    use polyisa_isadl::pred::{Pred, PredCtx};
    struct Ctx<'a> {
        is_rv64: bool,
        feats: u128,
        extra: &'a [String],
    }
    impl PredCtx for Ctx<'_> {
        fn flag(&self, name: &str) -> bool {
            if name == "rv64" {
                self.is_rv64
            } else if name == "rv32" {
                !self.is_rv64
            } else {
                self.extra
                    .iter()
                    .position(|f| f == name)
                    .is_some_and(|i| self.feats & (1u128 << i) != 0)
            }
        }
    }
    // 述語に現れる旗を集める（rv32/rv64 を除く）。
    fn flags(p: &Pred, out: &mut Vec<String>) {
        match p {
            Pred::True | Pred::False => {}
            Pred::Flag(n) => {
                if n != "rv32" && n != "rv64" && !out.contains(n) {
                    out.push(n.clone());
                }
            }
            Pred::Not(i) => flags(i, out),
            Pred::All(ps) | Pred::Any(ps) => {
                for q in ps {
                    flags(q, out);
                }
            }
        }
    }
    let mut fs = Vec::new();
    flags(pred, &mut fs);
    if fs.len() > 16 {
        return None;
    }
    // 排他宣言された機能を両方立てる組み合わせ（実在しない構成）を除く。
    let conflicts: Vec<(String, String)> = features
        .iter()
        .flat_map(|f| f.conflicts.iter().map(|c| (f.name.clone(), c.clone())))
        .collect();
    for is_rv64 in [true, false] {
        for combo in 0..(1u32 << fs.len()) {
            let mut feats = 0u128;
            for (b, f) in fs.iter().enumerate() {
                if combo & (1 << b) != 0 {
                    feats |= 1u128 << extra.iter().position(|e| e == f)?;
                }
            }
            let ctx = Ctx {
                is_rv64,
                feats,
                extra,
            };
            if conflicts.iter().any(|(a, b)| ctx.flag(a) && ctx.flag(b)) {
                continue;
            }
            if pred.eval(&ctx) {
                return Some((is_rv64, feats));
            }
        }
    }
    None
}

/// エンコードの往復テスト用のオペランド列を採取する。検査を通った
/// モデルの命令について、候補の直積から条件を満たすものを最大 `want`
/// 個返す。見つからなければ空。
fn sample_ops(
    insn: &polyisa_isadl::model::Insn,
    fmt: &polyisa_isadl::model::Format,
    fields: &std::collections::BTreeMap<&str, &polyisa_isadl::model::Field>,
    want: usize,
) -> Vec<Vec<u64>> {
    use polyisa_isadl::model::FieldKind;
    let fixed_bits = insn.pattern.bits() & insn.pattern.mask();
    // オペランドごとの候補値。
    let mut cands: Vec<Vec<u64>> = Vec::new();
    for op in &fmt.operands {
        let Some(f) = fields.get(op.field.as_deref().unwrap_or(op.name.as_str())) else {
            return Vec::new();
        };
        let cs: Vec<u64> = match &f.kind {
            FieldKind::Bits { hi, lo } => {
                let w = hi - lo + 1;
                // 語の中に収まるビット数。語外の論理ビットは 0 でなければ
                // ならず、候補の変形は語内の自由ビットだけで作る。
                let inw = insn.pattern.len().saturating_sub(*lo).min(w);
                let fmask: u128 = if inw >= 128 {
                    u128::MAX
                } else {
                    (1u128 << inw) - 1
                };
                // パターンの固定ビットと重なる位置は値が強制される。
                // 残りの自由ビットで変形を作る。
                let span: u128 = if w >= 128 {
                    u128::MAX
                } else {
                    ((1u128 << w) - 1) << lo
                };
                let fixmask = (insn.pattern.mask() & span) >> lo;
                let must = ((fixed_bits & span) >> lo) & fmask;
                let free = fmask & !fixmask;
                let mut v = vec![
                    must,
                    must | free.isolate_lowest_one(), // 最小の自由ビット
                    must | (free >> 1),               // 中間
                    must | free,                      // 全自由ビット
                ];
                v.retain(|x| *x <= fmask.min(u64::MAX as u128));
                v.dedup();
                v.iter().map(|x| *x as u64).collect()
            }
            FieldKind::Parts { parts, zfill } => {
                // 部ごとに強制ビットを求め、論理値の領域で変形する。
                let total: u32 = parts.iter().map(|(h, l)| h - l + 1).sum();
                let mut must = 0u64;
                let mut free = 0u64;
                let mut shift = total;
                for (hi, lo) in parts {
                    let w = hi - lo + 1;
                    shift -= w;
                    // 語の中に収まる分だけが値になる（語外の論理
                    // ビットは 0 を要求される）。
                    let inw = insn.pattern.len().saturating_sub(*lo).min(w);
                    if inw == 0 {
                        continue;
                    }
                    let pm: u64 = if inw >= 64 {
                        u64::MAX
                    } else {
                        (1u64 << inw) - 1
                    };
                    let span = ((1u128 << w) - 1) << lo;
                    let fix = ((insn.pattern.mask() & span) >> lo) as u64;
                    let have = ((fixed_bits & span) >> lo) as u64;
                    must |= (have & fix) << shift;
                    free |= (pm & !fix) << shift;
                }
                let xmax: u64 = if total >= 64 {
                    u64::MAX
                } else {
                    (1u64 << total) - 1
                };
                let zf = if *zfill >= 64 {
                    u64::MAX
                } else {
                    (1u64 << zfill) - 1
                };
                let mut v = vec![
                    must,
                    must | free.isolate_lowest_one(),
                    must | (free >> 1),
                    must | free,
                ];
                v.retain(|x| *x <= xmax);
                v.dedup();
                v.iter()
                    .map(|x| x << zfill)
                    .filter(|x| x & zf == 0)
                    .collect()
            }
            FieldKind::Hook { .. } => return Vec::new(),
        };
        // 強制ビットが u64 に収まらないなどで候補が空なら採取不能。
        if cs.is_empty() {
            return Vec::new();
        }
        cands.push(cs);
    }
    // 直積を試す（上限つき）。
    let mut out = Vec::new();
    let n = cands.len();
    let mut idx = vec![0usize; n];
    'outer: for _ in 0..4096 {
        let ops: Vec<u64> = (0..n).map(|i| cands[i][idx[i]]).collect();
        if encode_sim(insn, fmt, fields, &ops) {
            out.push(ops);
            if out.len() >= want {
                break;
            }
        }
        // odometer
        let mut i = n;
        loop {
            if i == 0 {
                break 'outer;
            }
            i -= 1;
            idx[i] += 1;
            if idx[i] < cands[i].len() {
                break;
            }
            idx[i] = 0;
        }
    }
    out
}

/// 生成コードと同じ規則でエンコード可否を判定する。往復入力の採取に使う。
fn encode_sim(
    insn: &polyisa_isadl::model::Insn,
    fmt: &polyisa_isadl::model::Format,
    fields: &std::collections::BTreeMap<&str, &polyisa_isadl::model::Field>,
    ops: &[u64],
) -> bool {
    use polyisa_isadl::model::{FieldKind, WhereOp, WhereRhs};
    if ops.len() != fmt.operands.len() {
        return false;
    }
    let mut word = insn.pattern.bits();
    for (i, op) in fmt.operands.iter().enumerate() {
        let Some(f) = fields.get(op.field.as_deref().unwrap_or(op.name.as_str())) else {
            return false;
        };
        let v = ops[i];
        match &f.kind {
            FieldKind::Bits { hi, lo } => {
                let w = hi - lo + 1;
                // 語の中に収まる分だけを比較し、語外のビットは 0 を要求する。
                let inw = insn.pattern.len().saturating_sub(*lo).min(w);
                if inw == 0 {
                    if v != 0 {
                        return false;
                    }
                    continue;
                }
                if inw < 64 && v >> inw != 0 {
                    return false;
                }
                let mask: u128 = if inw >= 128 {
                    u128::MAX
                } else {
                    (1u128 << inw) - 1
                };
                word |= (v as u128 & mask) << lo;
                if (word >> lo) & mask != v as u128 & mask {
                    return false;
                }
            }
            FieldKind::Parts { parts, zfill } => {
                let zf = if *zfill >= 64 {
                    u64::MAX
                } else {
                    (1u64 << zfill) - 1
                };
                if v & zf != 0 {
                    return false;
                }
                let x = v >> zfill;
                let total: u32 = parts.iter().map(|(h, l)| h - l + 1).sum();
                if total < 64 && x >= (1u64 << total) {
                    return false;
                }
                let mut shift = total;
                let mut back = 0u64;
                for (hi, lo) in parts {
                    let w = hi - lo + 1;
                    shift -= w;
                    // 語の中に収まる分だけを書き・読む。語外の論理
                    // ビットは back に入らず `back != x` が 0 を要求する。
                    let inw = insn.pattern.len().saturating_sub(*lo).min(w);
                    if inw == 0 {
                        continue;
                    }
                    let pm: u64 = if inw >= 64 {
                        u64::MAX
                    } else {
                        (1u64 << inw) - 1
                    };
                    word |= (((x >> shift) & pm) as u128) << lo;
                    back |= (((word >> lo) & pm as u128) as u64) << shift;
                }
                if back != x {
                    return false;
                }
            }
            FieldKind::Hook { .. } => return false,
        }
    }
    if !insn.pattern.matches(word) {
        return false;
    }
    let get = |name: &str| -> u128 {
        match fields.get(name) {
            Some(f) => match f.kind {
                FieldKind::Bits { hi, lo } => {
                    let w = hi - lo + 1;
                    let mask: u128 = if w >= 128 {
                        u128::MAX
                    } else {
                        (1u128 << w) - 1
                    };
                    (word >> lo) & mask
                }
                _ => 0,
            },
            None => 0,
        }
    };
    for w in &insn.wheres {
        let lhs = get(&w.field);
        let rhs = match &w.rhs {
            WhereRhs::Lit(v) => *v,
            WhereRhs::Field(n) => get(n),
        };
        let ok = match w.op {
            WhereOp::Eq => lhs == rhs,
            WhereOp::Ne => lhs != rhs,
            WhereOp::Lt => lhs < rhs,
            WhereOp::Le => lhs <= rhs,
            WhereOp::Gt => lhs > rhs,
            WhereOp::Ge => lhs >= rhs,
        };
        if !ok {
            return false;
        }
    }
    true
}

// Gap: GAP-0023 — 列挙経路（`model.insns`）のエンコーダ。`map` 経路
// （OpKind の逆変換）は 68k の EA 解釈と合わせて別段階で扱う。
fn gen_encoder(model: &Model) -> Result<String, GenError> {
    use polyisa_isadl::model::FieldKind;
    let mut s = String::from("// generated by isagen: encoder.\n");
    let fields: std::collections::BTreeMap<&str, &polyisa_isadl::model::Field> =
        model.fields.iter().map(|f| (f.name.as_str(), f)).collect();
    let formats: std::collections::BTreeMap<&str, &polyisa_isadl::model::Format> =
        model.formats.iter().map(|f| (f.name.as_str(), f)).collect();
    let extra = extra_flags(model)?;
    // `encode_*` の名前の一意性を先に確かめる（`to_snake` の衝突検査）。
    {
        let mut seen = std::collections::BTreeSet::new();
        for n in model
            .insns
            .iter()
            .map(|i| i.name.clone())
            .chain(map_insns(model).iter().map(|m| m.name.clone()))
        {
            if !seen.insert(to_snake(&n)) {
                return Err(GenError::Custom(format!("encode_* の名前が衝突する: {n}")));
            }
        }
    }
    for insn in &model.insns {
        let fmt = formats[insn.format.as_str()];
        s.push_str(&format!(
            "pub fn encode_{}(ops: &[u64]) -> Option<u128> {{\n",
            to_snake(&insn.name)
        ));
        if fmt.operands.is_empty() {
            s.push_str("    if !ops.is_empty() { return None; }\n");
        } else {
            s.push_str(&format!(
                "    if ops.len() != {} {{ return None; }}\n",
                fmt.operands.len()
            ));
        }
        // 書き込みが一つもない命令（オペランドなし、または全フィールドが
        // 語外）は `mut` を付けない。
        let writes = fmt.operands.iter().any(|op| {
            match &fields[op.field.as_deref().unwrap_or(op.name.as_str())].kind {
                FieldKind::Bits { hi, lo } => {
                    insn.pattern.len().saturating_sub(*lo).min(hi - lo + 1) > 0
                }
                FieldKind::Parts { parts, .. } => parts
                    .iter()
                    .any(|(h, l)| insn.pattern.len().saturating_sub(*l).min(h - l + 1) > 0),
                FieldKind::Hook { has_encoder } => *has_encoder,
            }
        });
        s.push_str(&format!(
            "    let {}word: u128 = {:#x};\n",
            if writes { "mut " } else { "" },
            insn.pattern.bits()
        ));
        for (i, op) in fmt.operands.iter().enumerate() {
            let f = fields[op.field.as_deref().unwrap_or(op.name.as_str())];
            match &f.kind {
                FieldKind::Bits { hi, lo } => {
                    let w = hi - lo + 1;
                    // 語の中に収まるビット数。語長を越える部分（圧縮命令が
                    // 幅広の形式を共有する場合）は書けず、0 を要求する。
                    let inw = insn.pattern.len().saturating_sub(*lo).min(w);
                    if inw == 0 {
                        s.push_str(&format!("    if ops[{i}] != 0 {{ return None; }}\n"));
                        continue;
                    }
                    let mask: u128 = if inw >= 128 {
                        u128::MAX
                    } else {
                        (1u128 << inw) - 1
                    };
                    s.push_str(&format!("    let v_{i} = ops[{i}];\n"));
                    if inw < 64 {
                        s.push_str(&format!("    if v_{i} >> {inw} != 0 {{ return None; }}\n"));
                    }
                    if *lo == 0 {
                        s.push_str(&format!("    word |= v_{i} as u128;\n"));
                        s.push_str(&format!(
                            "    if word & {mask:#x} != v_{i} as u128 {{ return None; }}\n"
                        ));
                    } else {
                        s.push_str(&format!("    word |= (v_{i} as u128) << {lo};\n"));
                        // 固定ビットが 1 の位置に 0 を置いた場合は読み戻しで
                        // ずれを検出する（0 を置いた位置はパターン検査が拾う）。
                        s.push_str(&format!(
                            "    if (word >> {lo}) & {mask:#x} != v_{i} as u128 {{ return None; }}\n"
                        ));
                    }
                }
                FieldKind::Parts { parts, zfill } => {
                    s.push_str(&format!("    let v_{i} = ops[{i}];\n"));
                    if *zfill > 0 {
                        let zf: u64 = if *zfill >= 64 {
                            u64::MAX
                        } else {
                            (1u64 << zfill) - 1
                        };
                        s.push_str(&format!("    if v_{i} & {zf:#x} != 0 {{ return None; }}\n"));
                        s.push_str(&format!("    let x_{i} = v_{i} >> {zfill};\n"));
                    } else {
                        s.push_str(&format!("    let x_{i} = v_{i};\n"));
                    }
                    let total: u32 = parts.iter().map(|(h, l)| h - l + 1).sum();
                    if total < 64 {
                        s.push_str(&format!(
                            "    if x_{i} >= {:#x} {{ return None; }}\n",
                            1u64 << total
                        ));
                    }
                    s.push_str(&parts_scatter(
                        parts,
                        &format!("x_{i}"),
                        "word",
                        insn.pattern.len(),
                    ));
                    // 読み戻しの一致検査。
                    let gather = parts_gather(parts, "word", "u64", insn.pattern.len());
                    s.push_str(&format!("    if ({gather}) != x_{i} {{ return None; }}\n"));
                }
                FieldKind::Hook { has_encoder } => {
                    if *has_encoder {
                        // フックの逆変換。`encode_field_<名>(word, v)` を
                        // ゲスト側が書く。
                        s.push_str(&format!(
                            "    word = encode_field_{}(word, ops[{i}])?;\n",
                            to_snake(&op.name)
                        ));
                    }
                }
            }
        }
        // `where` をエンコード時にも評価する。
        if !insn.wheres.is_empty() {
            let tag = format!("e_{}", to_snake(&insn.name));
            let (decls, conds) = where_decls_conds(model, insn, &tag);
            for d in decls {
                s.push_str(&format!("    {d}\n"));
            }
            s.push_str(&format!(
                "    if !({}) {{ return None; }}\n",
                conds.join(" && ")
            ));
        }
        // 最後に固定ビットとの一致を見る。
        s.push_str(&format!(
            "    if word & {:#x} != {:#x} {{ return None; }}\n",
            insn.pattern.mask(),
            insn.pattern.bits()
        ));
        s.push_str("    Some(word)\n}\n");
    }
    for mi in map_insns(model) {
        s.push_str(&format!(
            "pub fn encode_{}(ops: &[u64]) -> Option<u128> {{ let _ = ops; None }}\n",
            to_snake(&mi.name)
        ));
    }
    // 命令型からの振り分け。
    s.push_str("pub fn encode(insn: Insn, ops: &[u64]) -> Option<u128> {\n    match insn {\n");
    for insn in &model.insns {
        s.push_str(&format!(
            "        Insn::{} => encode_{}(ops),\n",
            to_ident(&insn.name),
            to_snake(&insn.name)
        ));
    }
    for mi in map_insns(model) {
        s.push_str(&format!(
            "        Insn::{} => encode_{}(ops),\n",
            to_ident(&mi.name),
            to_snake(&mi.name)
        ));
    }
    s.push_str("    }\n}\n");
    // 語から命令のオペランド値を取り出す。`encode` が受ける `ops` と同じ
    // 並び・同じ値域（語外のビットは 0）で返す。`Hook` を含む形式は
    // 取り出せないので空を返す。
    s.push_str("pub fn extract_ops(insn: Insn, word: u128) -> Vec<u64> {\n");
    let mut missing = !map_insns(model).is_empty();
    let mut arms = Vec::new();
    for insn in &model.insns {
        let fmt = formats[insn.format.as_str()];
        let mut pieces = Vec::new();
        let mut hook = false;
        for op in &fmt.operands {
            let f = fields[op.field.as_deref().unwrap_or(op.name.as_str())];
            match &f.kind {
                FieldKind::Bits { hi, lo } => {
                    let w = hi - lo + 1;
                    let mask: u128 = if w >= 128 {
                        u128::MAX
                    } else {
                        (1u128 << w) - 1
                    };
                    if *lo == 0 {
                        pieces.push(format!("(word & {mask:#x}) as u64"));
                    } else {
                        pieces.push(format!("((word >> {lo}) & {mask:#x}) as u64"));
                    }
                }
                FieldKind::Parts { parts, zfill } => {
                    let gather = parts_gather(parts, "word", "u64", u32::MAX);
                    if *zfill > 0 {
                        pieces.push(format!("({gather}) << {zfill}"));
                    } else {
                        pieces.push(gather);
                    }
                }
                FieldKind::Hook { .. } => {
                    hook = true;
                    break;
                }
            }
        }
        if hook {
            missing = true;
            continue;
        }
        arms.push(format!(
            "        Insn::{} => vec![{}],\n",
            to_ident(&insn.name),
            pieces.join(", ")
        ));
    }
    // `word` をどのアームも使わなければ未使用を避ける。
    if arms.is_empty() || arms.iter().all(|a| !a.contains("word")) {
        s.push_str("    let _ = word;\n");
    }
    s.push_str("    match insn {\n");
    for a in arms {
        s.push_str(&a);
    }
    if missing {
        s.push_str("        _ => vec![],\n");
    }
    s.push_str("    }\n}\n");
    // 往復テストの入力表。(命令, ops, 語長, is_rv64, feats)。採取できなかった
    // 命令は ENCODE_SKIPPED に名前を残す。
    s.push_str("pub const ENCODE_ROUNDTRIP: &[(Insn, &[u64], u32, bool, u128)] = &[\n");
    let mut skipped = Vec::new();
    for insn in &model.insns {
        let fmt = formats[insn.format.as_str()];
        let Some((is_rv64, feats)) = satisfy_when(&insn.when, &extra, &model.features) else {
            skipped.push(insn.name.clone());
            continue;
        };
        let cases = sample_ops(insn, fmt, &fields, 2);
        if cases.is_empty() {
            skipped.push(insn.name.clone());
            continue;
        }
        for ops in cases {
            s.push_str(&format!(
                "    (Insn::{}, &{:?}, {}, {}, {:#x}),\n",
                to_ident(&insn.name),
                ops,
                insn.pattern.len(),
                is_rv64,
                feats
            ));
        }
    }
    s.push_str("];\n");
    s.push_str("pub const ENCODE_SKIPPED: &[&str] = &[\n");
    for n in skipped {
        s.push_str(&format!("    {n:?},\n"));
    }
    s.push_str("];\n");
    Ok(s)
}

/// `map` を持つモデル用の、バイト列からのデコーダを生成する。
/// 表を持たないモデルでは空文字列を返す。
///
/// 生成するコードは、接頭辞の巡回、バイト値による表の選択、
/// オペランドのバイト消費（ModRM/SIB、変位、即値）の三段からなる。
/// 実行モードは `m64`（真偽）、`opd`（o16/o32）、`adr`（a16/a32/a64）
/// の三つを x86 系の約束として使う。
fn gen_map_decoder(model: &Model) -> Result<String, GenError> {
    use polyisa_isadl::model::{MapItem, ModeType};
    if model.maps.is_empty() {
        return Ok(String::new());
    }
    let mut s = String::from("// generated by isagen: byte map decoder.\n");

    // 実行モードのビット割り当て。`when` の旗名から式への対応も作る。
    let mut bit = 0u32;
    let mut mode_flags: Vec<(String, String)> = Vec::new();
    for m in &model.modes {
        match &m.ty {
            ModeType::Bool => {
                let c = format!("MODE_{}", name_const(&m.name));
                s.push_str(&format!("pub const {c}: u32 = {:#x};\n", 1u32 << bit));
                s.push_str(&format!(
                    "#[inline]\npub fn mode_{}(m: u32) -> bool {{ m & {c} != 0 }}\n",
                    to_snake(&m.name)
                ));
                mode_flags.push((m.name.clone(), format!("mode_{}(modes)", to_snake(&m.name))));
                bit += 1;
            }
            ModeType::Enum(vars) => {
                let width = (vars.len().max(1) as u32).saturating_sub(1);
                let width = 32 - width.leading_zeros();
                let c_sh = format!("MODE_{}_SHIFT", name_const(&m.name));
                let c_mask = format!("MODE_{}_MASK", name_const(&m.name));
                s.push_str(&format!("pub const {c_sh}: u32 = {bit};\n"));
                s.push_str(&format!(
                    "pub const {c_mask}: u32 = {:#x};\n",
                    (1u32 << width) - 1
                ));
                s.push_str(&format!(
                    "#[inline]\npub fn mode_{}(m: u32) -> u32 {{ (m >> {c_sh}) & {c_mask} }}\n",
                    to_snake(&m.name)
                ));
                for (i, v) in vars.iter().enumerate() {
                    let c = format!("MODE_{}_{}", name_const(&m.name), name_const(v));
                    s.push_str(&format!("pub const {c}: u32 = {i};\n"));
                    mode_flags.push((
                        format!("{}_{}", m.name, v),
                        format!("mode_{}(modes) == {c}", to_snake(&m.name)),
                    ));
                }
                bit += width;
            }
        }
    }

    // `when` の旗の解決順：機能（FEAT_*）→ 実行モードの旗。
    let extra = extra_flags(model)?;
    let mut flag_exprs: std::collections::BTreeMap<String, String> =
        std::collections::BTreeMap::new();
    for f in &extra {
        flag_exprs.insert(f.clone(), format!("feats & {} != 0", feat_const(f)));
    }
    for (name, expr) in mode_flags {
        flag_exprs.insert(name, expr);
    }

    // 生成コード内で使うオペランド種別の型。
    s.push_str(
        "#[derive(Clone, Copy)]\n\
         pub enum OpW { B8, W16, V, Z, J, D32, Q64, O128, A }\n\
         #[derive(Clone, Copy)]\n\
         pub enum OpK {\n\
         \x20   Ea(OpW), Reg(OpW), RegS, RegX, RmX, RegM, RmM,\n\
         \x20   InOp(OpW), Imm(OpW), Imm2(OpW), Rel(OpW), Moffs(OpW), Vv, RegT, RmT, VvT,\n\
         \x20   Imp(u8),\n\
         }\n",
    );

    // デコード結果。
    s.push_str(
        "/// オペコード表からデコードした命令。\n\
         #[derive(Clone, Copy, Debug, Default)]\n\
         pub struct MapDec {\n\
         \x20   /// デコードした命令。\n\
         \x20   pub insn: Insn,\n\
         \x20   /// 命令全体のバイト長。\n\
         \x20   pub len: u8,\n\
         \x20   /// オペコードバイト（+r 系のレジスタ番号の取り出しに使う）。\n\
         \x20   pub opcode: u8,\n\
         \x20   /// 最後の REX 接頭辞（なければ 0）。\n\
         \x20   pub rex: u8,\n\
         \x20   /// 0x66 オペランドサイズ接頭辞。\n\
         \x20   pub p66: bool,\n\
         \x20   /// 0x67 アドレスサイズ接頭辞。\n\
         \x20   pub p67: bool,\n\
         \x20   /// 0xF2/0xF3（0 はなし）。\n\
         \x20   pub rep: u8,\n\
         \x20   /// 0xF0 LOCK。\n\
         \x20   pub lock: bool,\n\
         \x20   /// セグメント上書きの接頭辞バイト（0 はなし）。\n\
         \x20   pub seg: u8,\n\
         \x20   /// ModRM バイト。\n\
         \x20   pub modrm: u8,\n\
         \x20   /// ModRM があったか。\n\
         \x20   pub has_modrm: bool,\n\
         \x20   /// SIB バイト。\n\
         \x20   pub sib: u8,\n\
         \x20   /// SIB があったか。\n\
         \x20   pub has_sib: bool,\n\
         \x20   /// EA の変位（符号拡張済み）。\n\
         \x20   pub disp: i64,\n\
         \x20   /// 変位のビット幅。\n\
         \x20   pub disp_bits: u8,\n\
         \x20   /// 即値・moffs（ゼロ拡張の生値）。\n\
         \x20   pub imm: u64,\n\
         \x20   /// 即値のビット幅。\n\
         \x20   pub imm_bits: u8,\n\
         \x20   /// 2 つ目の即値（ENTER）。\n\
         \x20   pub imm2: u64,\n\
         \x20   /// 分岐の相対変位（符号拡張済み）。\n\
         \x20   pub rel: i64,\n\
         \x20   /// 有効オペランドサイズ（16/32/64）。\n\
         \x20   pub osize: u8,\n\
         \x20   /// 有効アドレスサイズ（16/32/64）。\n\
         \x20   pub asize: u8,\n\
         \x20   /// デコードに使った実行モード。\n\
         \x20   pub modes: u32,\n\
         \x20   /// VEX 接頭辞があったか。\n\
         \x20   pub vex: bool,\n\
         \x20   /// VEX.mmmmm（表の選択コード）。\n\
         \x20   pub vex_map: u8,\n\
         \x20   /// VEX.L（ベクタ長 256 ビット）。\n\
         \x20   pub vex_l: bool,\n\
         \x20   /// VEX/EVEX.vvvv（反転済みのレジスタ番号。\n\
         \x20   /// EVEX では V' 込みで 0-31）。\n\
         \x20   pub vex_v: u8,\n\
         \x20   /// VEX.W（GPR 系の 64 ビット選択子）。\n\
         \x20   pub vex_w: bool,\n\
         \x20   /// EVEX 接頭辞があったか。\n\
         \x20   pub evex: bool,\n\
         \x20   /// EVEX.L'L（ベクタ長。0=128, 1=256, 2=512, 3 は予約）。\n\
         \x20   pub evex_ll: u8,\n\
         \x20   /// EVEX.b（broadcast/SAE/rounding-enable）。\n\
         \x20   pub evex_b: bool,\n\
         \x20   /// EVEX.z（ゼロイングマージ）。\n\
         \x20   pub evex_z: bool,\n\
         \x20   /// EVEX.aaa（マスクレジスタ k0-k7 の選択。0 はマスクなし）。\n\
         \x20   pub evex_aaa: u8,\n\
         \x20   /// EVEX.R'（ModRM.reg の 5 ビット目。反転済み）。\n\
         \x20   pub evex_r2: bool,\n\
         \x20   /// EVEX.map4 の U ビット（P1.2。メモリ形では\n\
         \x20   /// ~X4 として SIB 指標の 5 ビット目になる）。\n\
         \x20   /// map4 以外では予約の 1 なので常に真。\n\
         \x20   pub evex_u: bool,\n\
         \x20   /// APX の上位拡張ビット。REX2 のペイロード\n\
         \x20   /// [M0 R4 X4 B4 W R X B]、EVEX.map4 の\n\
         \x20   /// [0 ~R4 ~X4 B4 ...] が入る。bit7=M0（0F 表選択）、\n\
         \x20   /// bit6=R4・bit5=X4・bit4=B4（GPR 16-31 の拡張）。\n\
         \x20   /// 0 は REX2/map4 なし。\n\
         \x20   pub rex2: u8,\n\
         \x20   /// REX2 接頭辞を読んだか。ペイロード 0x00（全ビット\n\
         \x20   /// 0 の退化形）でも真になるので、REX2 の存在判定は\n\
         \x20   /// `rex2 != 0` ではなくこの旗を使う。\n\
         \x20   pub rex2_seen: bool,\n\
         \x20   /// EVEX.map4 の ND（vvvv が新しい宛先になる）。\n\
         \x20   pub ndd: bool,\n\
         \x20   /// EVEX.map4 の NF（フラグを更新しない）。\n\
         \x20   pub nf: bool,\n\
         }\n",
    );

    // 幅からバイト数への変換。V は即値では 64 ビットを 32 に落とす。
    s.push_str(
        "#[allow(clippy::all)]\n\
         #[inline]\n\
         fn opw_bits(w: OpW, osize: u8, m64: bool) -> u32 {\n\
         \x20   match w {\n\
         \x20       OpW::B8 => 8,\n\
         \x20       OpW::W16 => 16,\n\
         \x20       OpW::D32 => 32,\n\
         \x20       OpW::Q64 => 64,\n\
         \x20       OpW::O128 => 128,\n\
         \x20       OpW::Z => if osize == 16 { 16 } else { 32 },\n\
         \x20       OpW::J => if m64 { 32 } else if osize == 16 { 16 } else { 32 },\n\
         \x20       OpW::V => u32::from(osize),\n\
         \x20       OpW::A => 0,\n\
         \x20   }\n\
         }\n",
    );

    // ModRM/SIB/変位/即値の消費。
    s.push_str(
        "#[allow(clippy::all)]\n\
         fn modrm_dec(\n\
         \x20   bytes: &[u8],\n\
         \x20   i: &mut usize,\n\
         \x20   d: &mut MapDec,\n\
         \x20   edisp: u8,\n\
         \x20   ebok: u8,\n\
         ) -> Option<()> {\n\
         \x20   {\n\
         \x20       let m = *bytes.get(*i)?;\n\
         \x20       *i += 1;\n\
         \x20       d.has_modrm = true;\n\
         \x20       d.modrm = m;\n\
         \x20       // EVEX.b の合法性。レジスタ形は er（ebok bit1）、\n\
         \x20       // メモリ形は埋め込み broadcast（ebok bit0）を要求。\n\
         \x20       // それ以外で b=1 は予約で UD。\n\
         \x20       if d.evex_b {\n\
         \x20           let ok = if m >> 6 == 3 { ebok & 2 } else { ebok & 1 };\n\
         \x20           if ok == 0 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20       }\n\
         \x20       if m >> 6 != 3 {\n\
         \x20           let rm = m & 7;\n\
         \x20           let db: u32 = if d.asize == 16 {\n\
         \x20               match m >> 6 {\n\
         \x20                   0 if rm == 6 => 16,\n\
         \x20                   1 => 8,\n\
         \x20                   2 => 16,\n\
         \x20                   _ => 0,\n\
         \x20               }\n\
         \x20           } else {\n\
         \x20               if rm == 4 {\n\
         \x20                   let sib = *bytes.get(*i)?;\n\
         \x20                   *i += 1;\n\
         \x20                   d.has_sib = true;\n\
         \x20                   d.sib = sib;\n\
         \x20               }\n\
         \x20               match m >> 6 {\n\
         \x20                   0 if rm == 5 => 32,\n\
         \x20                   0 if rm == 4 && (d.sib & 7) == 5 => 32,\n\
         \x20                   1 => 8,\n\
         \x20                   2 => 32,\n\
         \x20                   _ => 0,\n\
         \x20               }\n\
         \x20           };\n\
         \x20           if db != 0 {\n\
         \x20               let nb = (db / 8) as usize;\n\
         \x20               let mut v: i64 = 0;\n\
         \x20               for k in 0..nb {\n\
         \x20                   v |= i64::from(*bytes.get(*i + k)?) << (k * 8);\n\
         \x20               }\n\
         \x20               *i += nb;\n\
         \x20               d.disp = v << (64 - db) >> (64 - db);\n\
         \x20               // EVEX は disp8 をオペランドサイズ N で\n\
         \x20               // スケールする（disp8*N）。edisp=0 はベクタ\n\
         \x20               // 全幅 16<<L'L。edisp!=0 は、broadcast 可能\n\
         \x20               // 項目（ebok bit0）では b=1 のときだけ要素\n\
         \x20               // バイト数に、それ以外（スカラ形）では常に\n\
         \x20               // 要素バイト数になる。\n\
         \x20               if d.evex && d.vex_map != 4 && db == 8 {\n\
         \x20                   let n = if edisp != 0 && (d.evex_b || ebok & 1 == 0) {\n\
         \x20                       i64::from(edisp)\n\
         \x20                   } else {\n\
         \x20                       16i64 << d.evex_ll\n\
         \x20                   };\n\
         \x20                   d.disp *= n;\n\
         \x20               }\n\
         \x20               d.disp_bits = db as u8;\n\
         \x20           }\n\
         \x20       }\n\
         \x20   }\n\
         \x20   Some(())\n\
         }\n\
         #[allow(clippy::all)]\n\
         fn finish(\n\
         \x20   bytes: &[u8],\n\
         \x20   i: &mut usize,\n\
         \x20   d: &mut MapDec,\n\
         \x20   insn: Insn,\n\
         \x20   ops: &[OpK],\n\
         \x20   group_modrm: bool,\n\
         \x20   edisp: u8,\n\
         \x20   ebok: u8,\n\
         \x20   pre: bool,\n\
         \x20   lock_ok: bool,\n\
         ) -> Option<Insn> {\n\
         \x20   let needs_modrm = group_modrm\n\
         \x20       || ops.iter().any(|o| {\n\
         \x20           matches!(\n\
         \x20               o,\n\
         \x20               OpK::Ea(_)\n\
         \x20                   | OpK::Reg(_)\n\
         \x20                   | OpK::RegS\n\
         \x20                   | OpK::RegX\n\
         \x20                   | OpK::RmX\n\
         \x20                   | OpK::RegM\n\
         \x20                   | OpK::RmM\n\
         \x20                   | OpK::RegT\n\
         \x20                   | OpK::RmT\n\
         \x20           )\n\
         \x20       });\n\
         \x20   if needs_modrm && !pre {\n\
         \x20       modrm_dec(bytes, i, d, edisp, ebok)?;\n\
         \x20   }\n\
         \x20   if d.lock && !(lock_ok && d.has_modrm && d.modrm >> 6 != 3) {\n\
         \x20       return None;\n\
         \x20   }\n\
         \x20   for op in ops {\n\
         \x20       match op {\n\
         \x20           OpK::Imm(w) => {\n\
         \x20               let bits = opw_bits(*w, d.osize, mode_m64(d.modes));\n\
         \x20               let nb = (bits / 8) as usize;\n\
         \x20               let mut v: u64 = 0;\n\
         \x20               for k in 0..nb {\n\
         \x20                   v |= u64::from(*bytes.get(*i + k)?) << (k * 8);\n\
         \x20               }\n\
         \x20               *i += nb;\n\
         \x20               d.imm = v;\n\
         \x20               d.imm_bits = bits as u8;\n\
         \x20           }\n\
         \x20           OpK::Imm2(w) => {\n\
         \x20               let bits = opw_bits(*w, d.osize, mode_m64(d.modes));\n\
         \x20               let nb = (bits / 8) as usize;\n\
         \x20               let mut v: u64 = 0;\n\
         \x20               for k in 0..nb {\n\
         \x20                   v |= u64::from(*bytes.get(*i + k)?) << (k * 8);\n\
         \x20               }\n\
         \x20               *i += nb;\n\
         \x20               d.imm2 = v;\n\
         \x20           }\n\
         \x20           OpK::Rel(w) => {\n\
         \x20               let bits = opw_bits(*w, d.osize, mode_m64(d.modes));\n\
         \x20               let nb = (bits / 8) as usize;\n\
         \x20               let mut v: i64 = 0;\n\
         \x20               for k in 0..nb {\n\
         \x20                   v |= i64::from(*bytes.get(*i + k)?) << (k * 8);\n\
         \x20               }\n\
         \x20               *i += nb;\n\
         \x20               d.rel = v << (64 - bits) >> (64 - bits);\n\
         \x20           }\n\
         \x20           OpK::Moffs(_) => {\n\
         \x20               let bits: u32 = match d.asize {\n\
         \x20                   16 => 16,\n\
         \x20                   64 => 64,\n\
         \x20                   _ => 32,\n\
         \x20               };\n\
         \x20               let nb = (bits / 8) as usize;\n\
         \x20               let mut v: u64 = 0;\n\
         \x20               for k in 0..nb {\n\
         \x20                   v |= u64::from(*bytes.get(*i + k)?) << (k * 8);\n\
         \x20               }\n\
         \x20               *i += nb;\n\
         \x20               d.imm = v;\n\
         \x20               d.imm_bits = bits as u8;\n\
         \x20           }\n\
         \x20           _ => {}\n\
         \x20       }\n\
         \x20   }\n\
         \x20   if *i > 15 {\n\
         \x20       return None;\n\
         \x20   }\n\
         \x20   d.len = *i as u8;\n\
         \x20   Some(insn)\n\
         }\n",
    );

    // 各表の選択関数。
    for map in &model.maps {
        s.push_str(&format!(
            "#[allow(clippy::all)]\n\
             fn sel_{}(bytes: &[u8], i: &mut usize, d: &mut MapDec, modes: u32, feats: u128) -> Option<Insn> {{\n",
            to_snake(&map.name)
        ));
        s.push_str("    let _ = feats;\n");
        s.push_str("    let _ = modes;\n");
        if map.postop {
            // postop 表（3DNow! の 0F 0F /r imm8 形式）は
            // ModRM（と SIB・変位）を先に読み、その後の
            // バイトを照合対象にする。ModRM の消費は
            // 候補のオペランドに依らず必ず行う。
            s.push_str("    modrm_dec(bytes, i, d, 0, 0)?;\n");
        }
        s.push_str("    let op = *bytes.get(*i)?; *i += 1;\n");
        s.push_str("    d.opcode = op;\n");
        s.push_str("    match op {\n");
        // バイト値ごとに項目を集める。
        let mut by_byte: std::collections::BTreeMap<u8, Vec<&MapItem>> =
            std::collections::BTreeMap::new();
        for item in &map.items {
            let key = match item {
                MapItem::Insn(b, _) | MapItem::Map(b, ..) => *b,
            };
            by_byte.entry(key).or_default().push(item);
        }
        for (byte, items) in &by_byte {
            s.push_str(&format!("        {byte:#04x} => {{\n"));
            // サブマップへの分岐はそのまま返す。分岐があるバイトは以降の
            // フォールスルーが到達不能になるので None を出さない。
            let mut has_branch = false;
            let mut gated = false;
            for item in items {
                if let MapItem::Map(_, name, when) = item {
                    // REX2・VEX・EVEX の後は 0F/0F38/0F3A の
                    // エスケープバイトを置けない（マップは M0 や
                    // mmmmm でだけ選ぶ）ので、サブマップへの分岐は
                    // レガシー経路に限る。
                    let guard = {
                        let g = when_guard_flags(when, &flag_exprs)?;
                        if g.is_empty() {
                            "!d.rex2_seen && !d.vex && !d.evex".to_string()
                        } else {
                            format!("({g}) && !d.rex2_seen && !d.vex && !d.evex")
                        }
                    };
                    s.push_str(&format!(
                        "            if {guard} {{\n                return sel_{}(bytes, i, d, modes, feats);\n            }}\n",
                        to_snake(name)
                    ));
                    gated = true;
                    has_branch = true;
                }
            }
            // 分岐がガード付きだとガード不成立時に命令項目へ落ちる。
            let has_branch = has_branch && !gated;
            // 命令項目。グループの有無で選び方が変わる。
            let insns: Vec<&polyisa_isadl::model::MapInsn> = items
                .iter()
                .filter_map(|it| match it {
                    MapItem::Insn(_, mi) => Some(mi),
                    _ => None,
                })
                .collect();
            let grouped: Vec<u8> = {
                let mut g: Vec<u8> = insns.iter().filter_map(|mi| mi.group).collect();
                g.sort_unstable();
                g.dedup();
                g
            };
            // ModRM.mod で選ぶ項目（group_mod）があれば、グループの
            // 有無にかかわらず ModRM バイトを覗く。postop 表では
            // 先読み済みの `d.modrm` を使う。
            if !grouped.is_empty()
                || insns
                    .iter()
                    .any(|mi| mi.group_mod.is_some() || mi.group_rm.is_some() || mi.sib)
            {
                if map.postop {
                    s.push_str("            let m = d.modrm;\n");
                } else {
                    s.push_str("            let m = *bytes.get(*i)?;\n");
                }
            }
            if !grouped.is_empty() {
                s.push_str("            let g = (m >> 3) & 7;\n            match g {\n");
                for g in &grouped {
                    s.push_str(&format!("                {g} => {{\n"));
                    for mi in insns.iter().filter(|mi| mi.group == Some(*g)) {
                        emit_map_candidate(&mut s, mi, &flag_exprs, map.postop)?;
                    }
                    s.push_str("                }\n");
                }
                s.push_str("                _ => {}\n            }\n");
            }
            for mi in insns.iter().filter(|mi| mi.group.is_none()) {
                emit_map_candidate(&mut s, mi, &flag_exprs, map.postop)?;
            }
            if !has_branch {
                s.push_str("            None\n");
            }
            s.push_str("        }\n");
        }
        s.push_str("        _ => None,\n    }\n}\n");
    }

    // 入口。
    s.push_str(
        "/// オペコード表によるデコード。`bytes` は命令の先頭からの\n\
         /// バイト列（15 バイトあれば全命令をカバーする）。\n\
         #[allow(clippy::all)]\n\
         pub fn decode_map(bytes: &[u8], modes: u32, feats: u128) -> Option<MapDec> {\n",
    );
    s.push_str("    let _ = feats;\n");
    s.push_str(
        "    let mut d = MapDec::default();\n\
         \x20   d.modes = modes;\n\
         \x20   let mut i = 0usize;\n\
         \x20   loop {\n\
         \x20       let b = *bytes.get(i)?;\n\
         \x20       match b {\n\
         \x20           0xF0 => d.lock = true,\n\
         \x20           0xF2 | 0xF3 => d.rep = b,\n\
         \x20           0x66 => d.p66 = true,\n\
         \x20           0x67 => d.p67 = true,\n\
         \x20           0x2E | 0x36 | 0x3E | 0x26 | 0x64 | 0x65 => d.seg = b,\n\
         \x20           _ => {\n\
         \x20               if mode_m64(modes) && (0x40..=0x4F).contains(&b) {\n\
         \x20                   d.rex = b;\n\
         \x20                   i += 1;\n\
         \x20                   if i > 15 {\n\
         \x20                       return None;\n\
         \x20                   }\n\
         \x20                   continue;\n\
         \x20               }\n\
         \x20               break;\n\
         \x20           }\n\
         \x20       }\n\
         \x20       d.rex = 0;\n\
         \x20       i += 1;\n\
         \x20       if i > 15 {\n\
         \x20           return None;\n\
         \x20       }\n\
         \x20   }\n",
    );
    // REX2 接頭辞（2 バイト、0xD5）。64 ビットモードでのみ。
    // ペイロード = [M0 R4 X4 B4 | W R X B]。下位ニブルは従来の
    // REX と同じなので `d.rex` に畳み、上位ニブルは `d.rex2` に残す。
    // 0xD5 は非64ビットでは AAD のオペコードなので m64 でだけ接頭辞。
    // REX2 自体は APX の機能。モデルが `apx` を宣言しているとき
    // だけ機能ゲートを掛け、他 ISA では従来どおり常時受理する。
    let apx_gate = if model.features.iter().any(|f| f.name == "apx") {
        format!(" && (feats & {} != 0)", feat_const("apx"))
    } else {
        String::new()
    };
    s.push_str(
        format!(
            "    {{\n\
             \x20       let b0 = *bytes.get(i)?;\n\
             \x20       if b0 == 0xD5 && mode_m64(modes){apx_gate} {{\n\
             \x20           let p = *bytes.get(i + 1)?;\n\
             \x20           // LOCK+REX2 は #UD。\n\
             \x20           if d.lock {{\n\
             \x20               return None;\n\
             \x20           }}\n\
             \x20           d.rex2 = p;\n\
             \x20           d.rex2_seen = true;\n\
             \x20           d.rex = 0x40 | (p & 0x0F);\n\
             \x20           i += 2;\n\
             \x20           if i > 15 {{\n\
             \x20               return None;\n\
             \x20           }}\n\
             \x20       }}\n\
             \x20   }}\n"
        )
        .as_str(),
    );
    // VEX 接頭辞（2/3 バイト）。VEX.R/X/B は REX と同じ拡張意味を
    // 持つので `d.rex` に畳み、VEX.pp は `d.p66`/`d.rep` に畳む。
    // 有効サイズの計算より先に解析して VEX.W を rex bit3 へ反映する。
    s.push_str(
        "    {\n\
         \x20       let b0 = *bytes.get(i)?;\n\
         \x20       if (b0 == 0xC4 || b0 == 0xC5) && !d.rex2_seen {\n\
         \x20           let b2 = *bytes.get(i + 1)?;\n\
         \x20           // 非64ビットモードでは直後の ModRM.mod==11 のときだけ\n\
         \x20           // VEX（さもなければ LES/LDS のオペコード）。\n\
         \x20           if mode_m64(modes) || b2 >> 6 == 3 {\n\
         \x20               // LOCK+VEX は #UD。\n\
         \x20               // VEX の前のレガシー接頭辞（66/F2/F3/LOCK）は\n\
         \x20               // #UD（XED 実測）。pp フィールドだけが接頭辞を選ぶ。\n\
         \x20               if d.lock || d.p66 || d.rep != 0 {\n\
         \x20                   return None;\n\
         \x20               }\n\
         \x20               d.rep = 0;\n\
         \x20               if b0 == 0xC5 {\n\
         \x20                   d.vex = true;\n\
         \x20                   d.vex_map = 1;\n\
         \x20                   // レジスタ拡張は 64 ビットモードでのみ有効。\n\
         \x20                   d.rex = if mode_m64(modes) {\n\
         \x20                       0x40 | (((b2 >> 7) & 1) ^ 1) << 2\n\
         \x20                   } else {\n\
         \x20                       0x40\n\
         \x20                   };\n\
         \x20                   d.vex_v = (!b2 >> 3) & 0xF;\n\
         \x20                   d.vex_l = b2 & 4 != 0;\n\
         \x20                   match b2 & 3 {\n\
         \x20                       1 => d.p66 = true,\n\
         \x20                       2 => d.rep = 0xF3,\n\
         \x20                       3 => d.rep = 0xF2,\n\
         \x20                       _ => {}\n\
         \x20                   }\n\
         \x20                   i += 2;\n\
         \x20               } else {\n\
         \x20                   let b3 = *bytes.get(i + 2)?;\n\
         \x20                   // VEX.mmmmm は 0F/0F38/0F3A（1-3）だけ有効。\n\
         \x20                   // 0 と 4 以上は予約で #UD（XOP 表の 8/9/10 は\n\
         \x20                   // 0x8F 接頭辞でのみ選ばれる）。\n\
         \x20                   if b2 & 0x1F == 0 || b2 & 0x1F > 3 {\n\
         \x20                       return None;\n\
         \x20                   }\n\
         \x20                   d.vex = true;\n\
         \x20                   d.vex_map = b2 & 0x1F;\n\
         \x20                   d.rex = if mode_m64(modes) {\n\
         \x20                       0x40\n\
         \x20                           | (((b2 >> 5) & 7) ^ 7)\n\
         \x20                           | ((b3 & 0x80) >> 4)\n\
         \x20                   } else {\n\
         \x20                       0x40\n\
         \x20                   };\n\
         \x20                   d.vex_w = b3 & 0x80 != 0;\n\
         \x20                   d.vex_v = (!b3 >> 3) & 0xF;\n\
         \x20                   d.vex_l = b3 & 4 != 0;\n\
         \x20                   match b3 & 3 {\n\
         \x20                       1 => d.p66 = true,\n\
         \x20                       2 => d.rep = 0xF3,\n\
         \x20                       3 => d.rep = 0xF2,\n\
         \x20                       _ => {}\n\
         \x20                   }\n\
         \x20                   i += 3;\n\
         \x20               }\n\
         \x20               if i > 15 {\n\
         \x20                   return None;\n\
         \x20               }\n\
         \x20           }\n\
         \x20       }\n\
         \x20   }\n",
    );
    // XOP 接頭辞（3 バイト、0x8F）。VEX と同じバイト並び
    // （RXB mmmmm / W vvvv L pp）で、mmmmm >= 8 のときだけ
    // 接頭辞になる — 8 未満なら POP Ev の ModRM なので
    // レガシー解読へ進む。マップ番号（8/9/10）は vex_code を
    // 持つ XOP 表に振り分ける。
    s.push_str(
        "    {\n\
         \x20   let b0 = *bytes.get(i)?;\n\
         \x20   if b0 == 0x8F && !d.vex && !d.evex && !d.rex2_seen {\n\
         \x20       let b2 = *bytes.get(i + 1)?;\n\
         \x20       if b2 & 0x1F >= 8 {\n\
         \x20           // レガシー接頭辞（66/F2/F3/LOCK）+XOP は #UD。\n\
         \x20           if d.lock || d.p66 || d.rep != 0 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20           let b3 = *bytes.get(i + 2)?;\n\
         \x20           d.vex = true;\n\
         \x20           d.vex_map = b2 & 0x1F;\n\
         \x20           d.rex = if mode_m64(modes) {\n\
         \x20               0x40 | (((b2 >> 5) & 7) ^ 7) | ((b3 & 0x80) >> 4)\n\
         \x20           } else {\n\
         \x20               0x40\n\
         \x20           };\n\
         \x20           d.vex_w = b3 & 0x80 != 0;\n\
         \x20           d.vex_v = (!b3 >> 3) & 0xF;\n\
         \x20           d.vex_l = b3 & 4 != 0;\n\
         \x20           // XOP の pp フィールドは予約で非 0 は #UD。\n\
         \x20           if b3 & 3 != 0 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20           i += 3;\n\
         \x20           if i > 15 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20       }\n\
         \x20   }\n\
         \x20   }\n",
    );
    // EVEX 接頭辞（4 バイト、0x62）。64 ビットモードでのみ扱う
    // （非64ビットでは BOUND との識別が別途必要）。
    // P0 = [~R ~X ~B ~R' 0 mm]、P1 = [W ~vvvv 1 pp]、
    // P2 = [z L' L b ~V' aaa]。R/X/B/V'/vvvv は反転格納。
    s.push_str(
        "    {\n\
         \x20       let b0 = *bytes.get(i)?;\n\
         \x20       if b0 == 0x62 && mode_m64(modes) && !d.vex && !d.rex2_seen {\n\
         \x20           let p0 = *bytes.get(i + 1)?;\n\
         \x20           let p1 = *bytes.get(i + 2)?;\n\
         \x20           let p2 = *bytes.get(i + 3)?;\n\
         \x20           let mmm = p0 & 7;\n\
         \x20           // LOCK+EVEX と予約ビット（P0.3=0、P1.2=1、mm!=0）は #UD。\n\
         \x20           // mmm は 3 ビット。4-7 のうち 4 は APX 昇格形（map4）。\n\
         \x20           // map4 では P0.3=B4・P0.4=~R4・P1.2=~X4 が有効フィールド\n\
         \x20           // なので予約ビット検査を緩める。5-7 は予約で、存在しない\n\
         \x20           // マップ番号としてディスパッチ側で #UD に落ちる。\n\
         \x20           if d.lock || mmm == 0 || d.p66 || d.rep != 0 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20           if mmm != 4 && (p0 & 0x08 != 0 || p1 & 4 == 0) {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20           d.evex = true;\n\
         \x20           d.vex_map = mmm;\n\
         \x20           d.rex = 0x40 | (((p0 >> 5) & 7) ^ 7) | ((p1 & 0x80) >> 4);\n\
         \x20           d.evex_r2 = p0 & 0x10 == 0;\n\
         \x20           d.vex_w = p1 & 0x80 != 0;\n\
         \x20           d.vex_v = ((!p1 >> 3) & 0xF) | (((!p2 >> 3) & 1) << 4);\n\
         \x20           if mmm == 4 {\n\
         \x20               // map4：P0.4 は R' ではなく ~R4、P0.3 は B4、\n\
         \x20               // P1.2 は ~X4。GPR 16-31 への拡張ビットを d.rex2 に\n\
         \x20               // REX2 と同じ並び（bit6=R4/bit5=X4/bit4=B4）で畳む。\n\
         \x20               // P2.4 は ND、P2.2 は NF、P2.1-0 は予約。\n\
         \x20               d.rex2 = (((!p0 >> 4) & 1) << 6)\n\
         \x20                   | (((!p1 >> 2) & 1) << 5)\n\
         \x20                   | ((p0 & 0x08) << 1);\n\
         \x20               d.evex_r2 = false;\n\
         \x20               d.ndd = p2 & 0x10 != 0;\n\
         \x20               d.nf = p2 & 4 != 0;\n\
         \x20           }\n\
         \x20           // U ビット（P1.2）。map4 以外では予約検査で\n\
         \x20           // 1 確定なので無条件に代入してよい。\n\
         \x20           d.evex_u = p1 & 4 != 0;\n\
         \x20           d.rep = 0;\n\
         \x20           match p1 & 3 {\n\
         \x20               1 => d.p66 = true,\n\
         \x20               2 => d.rep = 0xF3,\n\
         \x20               3 => d.rep = 0xF2,\n\
         \x20               _ => {}\n\
         \x20           }\n\
         \x20           d.evex_ll = (p2 >> 5) & 3;\n\
         \x20           d.evex_b = mmm != 4 && p2 & 0x10 != 0;\n\
         \x20           d.evex_z = p2 & 0x80 != 0;\n\
         \x20           d.evex_aaa = p2 & 7;\n\
         \x20           if d.evex_z && d.evex_aaa == 0 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20           i += 4;\n\
         \x20           if i > 15 {\n\
         \x20               return None;\n\
         \x20           }\n\
         \x20       }\n\
         \x20   }\n",
    );
    // 有効サイズ。
    s.push_str(
        "    d.osize = if mode_m64(modes) {\n\
         \x20       if d.rex & 0x08 != 0 {\n\
         \x20           64\n\
         \x20       } else if d.p66 {\n\
         \x20           16\n\
         \x20       } else {\n\
         \x20           32\n\
         \x20       }\n\
         \x20   } else if d.p66 {\n\
         \x20       if mode_opd(modes) == MODE_OPD_O16 { 32 } else { 16 }\n\
         \x20   } else if mode_opd(modes) == MODE_OPD_O16 {\n\
         \x20       16\n\
         \x20   } else {\n\
         \x20       32\n\
         \x20   };\n\
         \x20   d.asize = match (mode_adr(modes), d.p67) {\n\
         \x20       (MODE_ADR_A64, false) => 64,\n\
         \x20       (MODE_ADR_A64, true) | (MODE_ADR_A32, false) | (MODE_ADR_A16, true) => 32,\n\
         \x20       (MODE_ADR_A32, true) | (MODE_ADR_A16, false) => 16,\n\
         \x20       _ => 32,\n\
         \x20   };\n",
    );
    // VEX 経路では VEX.mmmmm が指す表へ進む。vex_code を持つ表から
    // ディスパッチを生成する。
    let mut vex_arms = String::new();
    for map in &model.maps {
        if let Some(code) = map.vex_code {
            vex_arms.push_str(&format!(
                "            {code} => sel_{}(bytes, &mut i, &mut d, modes, feats)?,\n",
                to_snake(&map.name)
            ));
        }
    }
    // REX2 の M0=1 は 0F 表を指す（0xD5 で 0F バイトを省略する）。
    // rex2_map1 の立った表が M0=1 のときの選択先。
    let mut m0_arm = String::new();
    for map in &model.maps {
        if map.rex2_map1 {
            m0_arm = format!(
                "    let insn = if d.rex2 & 0x80 != 0 {{\n\
                 \x20       sel_{}(bytes, &mut i, &mut d, modes, feats)?\n\
                 \x20   }} else {{\n",
                to_snake(&map.name)
            );
        }
    }
    if m0_arm.is_empty() {
        m0_arm = "    let insn = {\n".to_string();
    }
    s.push_str(&format!(
        "{m0_arm}         if d.vex || d.evex {{\n\
         \x20       match d.vex_map {{\n{vex_arms}            _ => return None,\n\
         \x20       }}\n\
         \x20   }} else {{\n\
         \x20       sel_primary(bytes, &mut i, &mut d, modes, feats)?\n\
         \x20   }}\n\
         \x20   }};\n\
         \x20   // REX2 の予約行。M0=0（primary）では 0x4*/0x7*/0xE*\n\
         \x20   // と 0xA*（0xA1=JMPABS 以外）、M0=1（0F 表）では\n\
         \x20   // 0x3*/0x8* の行が #UD。\n\
         \x20   if d.rex2_seen && !d.evex {{\n\
         \x20       let row = d.opcode >> 4;\n\
         \x20       let bad = if d.rex2 & 0x80 != 0 {{\n\
         \x20           row == 3 || row == 8\n\
         \x20       }} else {{\n\
         \x20           row == 4 || row == 7 || row == 0xE || (row == 0xA && d.opcode != 0xA1)\n\
         \x20       }};\n\
         \x20       if bad {{\n\
         \x20           return None;\n\
         \x20       }}\n\
         \x20   }}\n\
         \x20   d.insn = insn;\n\
         \x20   Some(d)\n\
         }}\n",
    ));
    Ok(s)
}

/// `map` の命令項目の選択コードを生成する。`pfx`・`when` の検査を
/// 先に行い、通れば `finish` でオペランドを消費する。
fn emit_map_candidate(
    s: &mut String,
    mi: &polyisa_isadl::model::MapInsn,
    flag_exprs: &std::collections::BTreeMap<String, String>,
    postop: bool,
) -> Result<(), GenError> {
    use polyisa_isadl::model::PfxSel;
    let pfx = match mi.pfx {
        PfxSel::Any => "true".to_string(),
        PfxSel::Plain => "!d.p66 && d.rep == 0".to_string(),
        PfxSel::No66 => "!d.p66 && d.rep == 0".to_string(),
        PfxSel::No66F3 => "!d.p66 && d.rep == 0".to_string(),
        PfxSel::NoF2 => "d.rep == 0".to_string(),
        PfxSel::NoF3 => "d.rep != 0xF3".to_string(),
        PfxSel::NoF2F3 => "d.rep == 0".to_string(),
        PfxSel::P66 => "d.p66 && d.rep == 0".to_string(),
        PfxSel::PF2 => "d.rep == 0xF2".to_string(),
        PfxSel::PF3 => "d.rep == 0xF3".to_string(),
    };
    let guard = when_guard_flags(&mi.when, flag_exprs)?;
    // VEX/EVEX/レガシー項目はそれぞれの経路でのみ選ぶ。
    // EVEX 項目は更に L'L の許容集合を検査する（ll=3 はどの
    // 集合にも含まれないので常に拒否される）。
    use polyisa_isadl::model::VexL;
    let vex = if mi.promoted {
        // APX 昇格形（EVEX.map4）：z=0・L'L=0・P2.1-0=0 を要求
        // （P2.4=ND・P2.2=NF はフィールド）。表番号 4 への到達は
        // ディスパッチ側で確定済み。`ndd_req` は vvvv を被演算子に
        // 使う形（PUSH2/POP2 など）で ND=1 を必須にする。
        // ND=0 の通常形は vvvv が未使用（格納フィールド全 1、
        // 反転済みでは 0）を要求する。NF は `nf_ok` の項目でのみ
        // 受理。`zu` は ND=1 かつ vvvv 未使用を要求（vvvv は
        // レジスタを指さず、ND は ZU を選ぶ）。
        let mut c = String::from("d.evex && !d.evex_z && d.evex_ll == 0 && d.evex_aaa & 3 == 0");
        // U ビット（~X4）はメモリ形でのみ有効フィールド。
        // mod=11 では予約の 1 でなければ #UD（XED 実測）。
        let modreg = if mi.group.is_some() || mi.group_mod.is_some() || mi.group_rm.is_some() {
            "m >> 6 == 3"
        } else if postop {
            "d.modrm >> 6 == 3"
        } else {
            "*bytes.get(*i)? >> 6 == 3"
        };
        c.push_str(&format!(" && (d.evex_u || !({modreg}))"));
        if !mi.nf_ok {
            c.push_str(" && !d.nf");
        }
        if mi.zu {
            c.push_str(" && d.ndd && d.vex_v == 0");
        } else {
            c.push_str(" && (d.ndd || d.vex_v == 0)");
        }
        if mi.ndd_req {
            c.push_str(" && d.ndd");
        }
        c
    } else {
        match (mi.vex, mi.evex) {
            (None, None) => "!d.vex && !d.evex".to_string(),
            (Some(VexL::Any), None) => "d.vex".to_string(),
            (Some(VexL::L0), None) => "d.vex && !d.vex_l".to_string(),
            (Some(VexL::L1), None) => "d.vex && d.vex_l".to_string(),
            (None, Some(mask)) => {
                if mi.er {
                    // {er} 形（b=1 + レジスタ形）では L'L は丸め指定
                    // なので全値を受理する。レジスタ形の判定は、非グループ
                    // 項目では `bytes[i]`（=ModRM バイト）の mod、グループ
                    // 項目では定義済みの `m` を見る。postop 表では ModRM が
                    // 先読み済みなので `d.modrm` を使う（現状 er は
                    // vex_code のある表にだけ置けるので到達不能だが）。
                    let modreg =
                        if mi.group.is_some() || mi.group_mod.is_some() || mi.group_rm.is_some() {
                            "m >> 6 == 3".to_string()
                        } else if postop {
                            "d.modrm >> 6 == 3".to_string()
                        } else {
                            "*bytes.get(*i)? >> 6 == 3".to_string()
                        };
                    format!(
                        "d.evex && ((1u32 << d.evex_ll) & {mask} != 0 || (d.evex_b && {modreg}))"
                    )
                } else {
                    format!("d.evex && (1u32 << d.evex_ll) & {mask} != 0")
                }
            }
            (Some(_), Some(_)) => {
                return Err(GenError::Custom(format!("{}: vex と evex は排他", mi.name)));
            }
        }
    };
    // `vex_rv` はフィールド 1111b（= 補数を解くとレジスタ 0）を要求。
    let vex = if mi.vex_rv {
        format!("{vex} && d.vex_v == 0")
    } else {
        vex
    };
    // `wsel` は VEX/EVEX.W の値で項目を分ける。
    let vex = if let Some(w) = mi.wsel {
        format!("{vex} && d.vex_w == {w}")
    } else {
        vex
    };
    let mut cond = if guard.is_empty() {
        format!("({vex}) && ({pfx})")
    } else {
        format!("({vex}) && ({pfx}) && ({guard})")
    };
    // グループ項目の mod 選択（`m` はグループ生成部が定義済み）。
    cond = match mi.group_mod {
        Some(true) => format!("(m >> 6) == 3 && ({cond})"),
        Some(false) => format!("(m >> 6) != 3 && ({cond})"),
        None => cond,
    };
    // sibmem（mod!=11 かつ r/m=100）を要求する項目（AMX タイル）。
    if mi.sib {
        cond = format!("(m >> 6) != 3 && (m & 7) == 4 && ({cond})");
    }
    // グループ項目の r/m 副選択（mod=11 内の更なる分岐）。
    if let Some(rm) = mi.group_rm {
        cond = format!("(m & 7) == {rm} && ({cond})");
    }
    let ops = mi.ops.iter().map(opk_code).collect::<Vec<_>>().join(", ");
    let group = mi.group.is_some();
    let edisp = mi.edisp;
    let ebok = u8::from(mi.bcast) | (u8::from(mi.er) << 1);
    s.push_str(&format!(
        "            if {cond} {{\n                return finish(bytes, i, d, Insn::{}, &[{ops}], {group}, {edisp}, {ebok}, {postop}, {});\n            }}\n",
        to_ident(&mi.name),
        mi.lock_ok
    ));
    Ok(())
}

/// モデルの `OpKind` を生成コードの `OpK` リテラルにする。
fn opk_code(op: &polyisa_isadl::model::OpKind) -> String {
    use polyisa_isadl::model::{ImpOp, OpKind, OpWidth};
    fn wc(w: &OpWidth) -> &'static str {
        match w {
            OpWidth::B8 => "OpW::B8",
            OpWidth::W16 => "OpW::W16",
            OpWidth::V => "OpW::V",
            OpWidth::Z => "OpW::Z",
            OpWidth::J => "OpW::J",
            OpWidth::D32 => "OpW::D32",
            OpWidth::Q64 => "OpW::Q64",
            OpWidth::O128 => "OpW::O128",
            OpWidth::A => "OpW::A",
        }
    }
    fn imp(i: &ImpOp) -> u8 {
        match i {
            ImpOp::Eax => 0,
            ImpOp::Ecx => 1,
            ImpOp::Edx => 2,
            ImpOp::Ebx => 3,
            ImpOp::Esp => 4,
            ImpOp::Ebp => 5,
            ImpOp::Esi => 6,
            ImpOp::Edi => 7,
            ImpOp::Cl => 8,
            ImpOp::One => 9,
            ImpOp::St0 => 10,
            ImpOp::Sti => 11,
            ImpOp::Xsrc => 12,
            ImpOp::Ydst => 13,
            ImpOp::Seg(n) => 0x20 + n,
        }
    }
    match op {
        OpKind::Ea(w) => format!("OpK::Ea({})", wc(w)),
        OpKind::Reg(w) => format!("OpK::Reg({})", wc(w)),
        OpKind::RegS => "OpK::RegS".to_string(),
        OpKind::RegX => "OpK::RegX".to_string(),
        OpKind::RmX => "OpK::RmX".to_string(),
        OpKind::RegM => "OpK::RegM".to_string(),
        OpKind::RmM => "OpK::RmM".to_string(),
        OpKind::InOp(w) => format!("OpK::InOp({})", wc(w)),
        OpKind::Imm(w) => format!("OpK::Imm({})", wc(w)),
        OpKind::Imm2(w) => format!("OpK::Imm2({})", wc(w)),
        OpKind::Rel(w) => format!("OpK::Rel({})", wc(w)),
        OpKind::Moffs(w) => format!("OpK::Moffs({})", wc(w)),
        OpKind::Vv => "OpK::Vv".to_string(),
        OpKind::RegT => "OpK::RegT".to_string(),
        OpKind::RmT => "OpK::RmT".to_string(),
        OpKind::VvT => "OpK::VvT".to_string(),
        OpKind::Imp(i) => format!("OpK::Imp({})", imp(i)),
    }
}

/// `when` の述語を、機能旗と実行モードの式の表に対して評価する
/// Rust 式にする。
fn when_guard_flags(
    pred: &polyisa_isadl::pred::Pred,
    flag_exprs: &std::collections::BTreeMap<String, String>,
) -> Result<String, GenError> {
    use polyisa_isadl::pred::Pred;
    match pred {
        Pred::True => Ok(String::new()),
        Pred::False => Ok("false".to_string()),
        Pred::Flag(name) => flag_exprs
            .get(name)
            .cloned()
            .ok_or_else(|| GenError::UnsupportedWhen(name.clone())),
        Pred::Not(inner) => Ok(format!("!({})", when_guard_flags(inner, flag_exprs)?)),
        Pred::All(ps) => {
            let mut parts = Vec::new();
            for p in ps {
                parts.push(format!("({})", when_guard_flags(p, flag_exprs)?));
            }
            Ok(parts.join(" && "))
        }
        Pred::Any(ps) => {
            let mut parts = Vec::new();
            for p in ps {
                parts.push(format!("({})", when_guard_flags(p, flag_exprs)?));
            }
            Ok(parts.join(" || "))
        }
    }
}

/// 名前を生成コードの定数名の一部にする（`m64` → `M64`）。
fn name_const(name: &str) -> String {
    let mut s = String::new();
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            s.push(c.to_ascii_uppercase());
        } else {
            s.push('_');
        }
    }
    s
}

fn gen_operands(model: &Model) -> String {
    let mut s = String::from(
        "// generated by isagen: operands. 32ビット長の形式だけを扱う。\n// 圧縮形式の取り出しは形式の追加後に生成する。\n",
    );
    enum Item {
        Bits(u32, u32),
        Parts(Vec<(u32, u32)>, u32),
    }
    for fmt in &model.formats {
        // フィールド名と、取り出す種別（Bits は u32、Parts は u64）。
        let mut items: Vec<(String, Item)> = Vec::new();
        for fname in &fmt.fields {
            let Some(f) = model.fields.iter().find(|f| f.name == *fname) else {
                continue;
            };
            let item = match &f.kind {
                polyisa_isadl::model::FieldKind::Bits { hi, lo } => Item::Bits(*hi, *lo),
                polyisa_isadl::model::FieldKind::Parts { parts, zfill } => {
                    Item::Parts(parts.clone(), *zfill)
                }
                _ => continue,
            };
            items.push((fname.clone(), item));
        }
        if items.is_empty() {
            continue;
        }
        let ty = format!("Ops{}", to_ident(&fmt.name));
        let f = format!("ops_{}", to_snake(&fmt.name));
        s.push_str(&format!("pub struct {ty} {{ pub raw: u128,"));
        for (name, item) in &items {
            let t = match item {
                Item::Bits(..) => "u32",
                Item::Parts(..) => "u64",
            };
            s.push_str(&format!(" pub {name}: {t},"));
        }
        s.push_str(" }\n");
        s.push_str(&format!("pub fn {f}(word: u128) -> {ty} {{\n"));
        for (name, item) in &items {
            match item {
                Item::Bits(hi, lo) => {
                    let width = hi - lo + 1;
                    let mask: u128 = if width >= 128 {
                        u128::MAX
                    } else {
                        (1u128 << width) - 1
                    };
                    if *lo == 0 {
                        s.push_str(&format!("    let {name} = (word & {mask:#x}) as u32;\n"));
                    } else {
                        s.push_str(&format!(
                            "    let {name} = ((word >> {lo}) & {mask:#x}) as u32;\n"
                        ));
                    }
                }
                Item::Parts(parts, zfill) => {
                    // 取り出しは語の実値にだけ触るので語長で絞らない。
                    let gather = parts_gather(parts, "word", "u64", u32::MAX);
                    if *zfill > 0 {
                        s.push_str(&format!("    let {name} = ({gather}) << {zfill};\n"));
                    } else {
                        s.push_str(&format!("    let {name} = {gather};\n"));
                    }
                }
            }
        }
        s.push_str(&format!("    {ty} {{ raw: word,"));
        for (name, _) in &items {
            s.push_str(&format!(" {name},"));
        }
        s.push_str(" }\n}\n");
    }
    s
}

fn gen_metadata(model: &Model) -> String {
    let mut s = String::from("// generated by isagen: metadata.\n");
    s.push_str("pub struct InsnMeta { pub name: &'static str, pub timing: &'static str }\n");
    s.push_str("pub const INSNS: &[InsnMeta] = &[\n");
    for insn in &model.insns {
        s.push_str(&format!(
            "    InsnMeta {{ name: {:?}, timing: {:?} }},\n",
            insn.name, insn.timing
        ));
    }
    for mi in map_insns(model) {
        s.push_str(&format!(
            "    InsnMeta {{ name: {:?}, timing: {:?} }},\n",
            mi.name, mi.timing
        ));
    }
    s.push_str("];\n");
    s.push_str("pub const FEATURES: &[&str] = &[\n");
    for f in &model.features {
        s.push_str(&format!("    {:?},\n", f.name));
    }
    s.push_str("];\n");
    // 機能の宣言全体（implies/conflicts 込み）。`--cpu` の解決が使う。
    s.push_str("pub const FEATURE_DEFS: &[(&str, &[&str], &[&str])] = &[\n");
    for f in &model.features {
        let list = |v: &[String]| {
            let inner = v
                .iter()
                .map(|s| format!("{s:?}"))
                .collect::<Vec<_>>()
                .join(", ");
            format!("&[{inner}]")
        };
        s.push_str(&format!(
            "    ({:?}, {}, {}),\n",
            f.name,
            list(&f.implies),
            list(&f.conflicts)
        ));
    }
    s.push_str("];\n");
    s.push_str("pub const MODELS: &[&str] = &[\n");
    for m in &model.models {
        s.push_str(&format!("    {:?},\n", m.name));
    }
    s.push_str("];\n");
    // CPU モデルの定義全体（親と機能の足し引きと識別情報）。
    // `--cpu` の解決が使う。
    s.push_str(
        "/// `MODEL_DEFS` の行型（名前、親、追加機能、削除機能、識別情報の対）。\n\
         pub type ModelRow = (\n    &'static str,\n    &'static str,\n    &'static [&'static str],\n    &'static [&'static str],\n    &'static [(&'static str, &'static str)],\n);\n",
    );
    s.push_str("pub const MODEL_DEFS: &[ModelRow] = &[\n");
    for m in &model.models {
        let list = |v: &[String]| {
            let inner = v
                .iter()
                .map(|s| format!("{s:?}"))
                .collect::<Vec<_>>()
                .join(", ");
            format!("&[{inner}]")
        };
        let ident = m
            .ident
            .iter()
            .map(|(k, v)| format!("({k:?}, {v:?})"))
            .collect::<Vec<_>>()
            .join(", ");
        s.push_str(&format!(
            "    ({:?}, {:?}, {}, {}, &[{ident}]),\n",
            m.name,
            m.parent,
            list(&m.add_features),
            list(&m.remove_features)
        ));
    }
    s.push_str("];\n");
    // 機能→識別情報ビットの対応表（cpu-models.md の `cpuid_bit`）。
    // `--cpu` の機能集合からリーフごとの値を導出する実行側が読む。
    s.push_str("pub const IDENT_BITS: &[(&str, u32, u32, &str, u8)] = &[\n");
    for b in &model.ident_bits {
        s.push_str(&format!(
            "    ({:?}, {:#x}, {}, {:?}, {}),\n",
            b.feature, b.leaf, b.subleaf, b.reg, b.bit
        ));
    }
    s.push_str("];\n");
    s.push_str(&format!(
        "pub const DEFAULT_FEATS: u128 = {:#x};\n",
        default_feats(model)
    ));
    s.push_str(&params_code(model));
    s
}

/// パラメータ値（文字列）を `u64` の格納ビットにする。
fn param_bits(kind: &polyisa_isadl::model::ParamKind, v: &str) -> u64 {
    use polyisa_isadl::model::ParamKind::*;
    match kind {
        Bool => u64::from(v == "true"),
        Enum(vs) => vs
            .iter()
            .position(|x| x == v)
            .expect("validated enum variant") as u64,
        Int(_) => v.parse().expect("validated int"),
    }
}

/// `ParamKind` の生成コードでのフィールド型。
fn param_ty(kind: &polyisa_isadl::model::ParamKind) -> &'static str {
    use polyisa_isadl::model::ParamKind::*;
    match kind {
        Bool => "bool",
        Enum(_) => "u8",
        Int(_) => "u32",
    }
}

/// パラメータ値（文字列）を生成コードのリテラルにする。
fn param_lit(kind: &polyisa_isadl::model::ParamKind, v: &str) -> String {
    use polyisa_isadl::model::ParamKind::*;
    match kind {
        Bool => v.to_string(),
        Enum(vs) => vs
            .iter()
            .position(|x| x == v)
            .expect("validated enum variant")
            .to_string(),
        Int(_) => v.to_string(),
    }
}

/// CPU モデル名から挙動パラメータを解決した `Params` の生成。
/// 親チェーンを根から順にたどり、子の値で上書きする。
fn params_code(model: &Model) -> String {
    if model.params.is_empty() {
        return String::new();
    }
    let mut s = String::from(
        "/// CPU モデルごとの挙動パラメータ（`cpu-models.md` の `param`）。
         /// フィールドの型は宣言の型に従い、列挙は列挙子の序数である。
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]
         pub struct Params {
",
    );
    for p in &model.params {
        let doc = if p.doc.is_empty() {
            p.name.clone()
        } else {
            format!("{}: {}", p.name, p.doc)
        };
        s.push_str(&format!(
            "    /// {doc}
    pub {}: {},
",
            p.name,
            param_ty(&p.kind)
        ));
    }
    s.push_str(
        "}
",
    );
    // `Default` は宣言の既定値（先頭モデルの値ではない）にする。
    let defs = model
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name, param_lit(&p.kind, &p.default)))
        .collect::<Vec<_>>()
        .join(", ");
    s.push_str(&format!(
        "#[allow(clippy::derivable_impls)]
         impl Default for Params {{
    fn default() -> Self {{ Params {{ {defs} }} }}
}}
"
    ));
    // `Backend::param` で読むためのマーカー型をパラメータごとに出す。
    for p in &model.params {
        let ty = p
            .name
            .split('_')
            .map(|w| {
                let mut c = w.chars();
                c.next()
                    .map(|f| f.to_uppercase().collect::<String>())
                    .unwrap_or_default()
                    + c.as_str()
            })
            .collect::<String>();
        let vty = param_ty(&p.kind);
        let from = match &p.kind {
            polyisa_isadl::model::ParamKind::Bool => "v != 0".to_string(),
            _ => format!("v as {vty}"),
        };
        let def = param_bits(&p.kind, &p.default);
        s.push_str(&format!(
            "/// `{name}` を `Backend::param` で読むためのマーカー型。
             pub struct {ty}Param;
             impl polyisa_sem::Param for {ty}Param {{
                 type Value = {vty};
                 fn from_bits(v: u64) -> {vty} {{ {from} }}
                 fn default_bits() -> u64 {{ {def} }}
             }}
",
            name = p.name,
        ));
    }
    // `Params` をバックエンドのパラメータ表に流し込む関数。
    s.push_str(
        "/// `Params` の値をバックエンドのパラメータ表に流し込む。
         /// 実行・翻訳の開始時に一度呼ぶ。
         pub fn install_params<B: polyisa_sem::Backend>(b: &mut B, p: &Params) {
",
    );
    for p in &model.params {
        let ty = p
            .name
            .split('_')
            .map(|w| {
                let mut c = w.chars();
                c.next()
                    .map(|f| f.to_uppercase().collect::<String>())
                    .unwrap_or_default()
                    + c.as_str()
            })
            .collect::<String>();
        s.push_str(&format!(
            "    b.set_param::<{ty}Param>(u64::from(p.{name}));
",
            name = p.name
        ));
    }
    s.push_str(
        "}
",
    );
    // 翻訳キーに畳む値。フィールドが増えてもここだけ直せばよい。
    s.push_str(
        "/// `Translate::key` に畳むための、全フィールドを混ぜた値。
         pub fn params_key(p: &Params) -> u64 {
    let mut h = 0x9e37_79b9_7f4a_7c15u64;
",
    );
    for p in &model.params {
        s.push_str(&format!(
            "    h = h.rotate_left(5) ^ u64::from(p.{});
",
            p.name
        ));
    }
    s.push_str(
        "    h
}
",
    );
    // 列挙パラメータの列挙子を定数として出す（呼び出し側が序数を
    // 直書きしないようにする）。
    for p in &model.params {
        if let polyisa_isadl::model::ParamKind::Enum(vs) = &p.kind {
            for (i, v) in vs.iter().enumerate() {
                s.push_str(&format!(
                    "pub const {}_{}: u8 = {i};
",
                    p.name.to_uppercase(),
                    v.to_uppercase()
                ));
            }
        }
    }
    // モデル名 → 解決済み値。
    fn resolve<'a>(
        model: &'a Model,
        d: &'a polyisa_isadl::model::ModelDef,
    ) -> std::collections::BTreeMap<&'a str, &'a str> {
        let mut chain = vec![d];
        let mut cur = d;
        let mut guard = model.models.len() + 1;
        while !cur.parent.is_empty() && guard > 0 {
            guard -= 1;
            cur = model
                .models
                .iter()
                .find(|m| m.name == cur.parent)
                .expect("model parent");
            chain.push(cur);
        }
        let mut vals: std::collections::BTreeMap<&'a str, &'a str> =
            std::collections::BTreeMap::new();
        for p in &model.params {
            vals.insert(p.name.as_str(), p.default.as_str());
        }
        for row in chain.iter().rev() {
            for (k, v) in &row.params {
                vals.insert(k.as_str(), v.as_str());
            }
        }
        vals
    }
    let lit = |m: &polyisa_isadl::model::ModelDef| {
        let vals = resolve(model, m);
        let fields = model
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, param_lit(&p.kind, vals[p.name.as_str()])))
            .collect::<Vec<_>>()
            .join(", ");
        format!("Params {{ {fields} }}")
    };
    let first = model
        .models
        .first()
        .map(lit)
        .unwrap_or_else(|| "Params::default()".to_string());
    s.push_str(&format!(
        "pub const DEFAULT_PARAMS: Params = {first};
"
    ));
    s.push_str(
        "/// CPU モデル名から挙動パラメータを解決する。未知の名前は既定値。
         pub fn model_params(name: &str) -> Params {
    match name {
",
    );
    for m in &model.models {
        s.push_str(&format!(
            "        {:?} => {},
",
            m.name,
            lit(m)
        ));
    }
    s.push_str(
        "        _ => DEFAULT_PARAMS,
    }
}

/// CPU モデル名から機能ビットマスクを解決する。親連鎖をたどって
/// add/remove を適用し、機能の `implies` で閉包を取る。
/// 未知の名前は DEFAULT_FEATS。
pub fn model_feats(name: &str) -> u128 {
    let mut chain: Vec<&ModelRow> = Vec::new();
    let mut cur = name;
    loop {
        let Some(row) = MODEL_DEFS.iter().find(|r| r.0 == cur) else {
            return DEFAULT_FEATS;
        };
        chain.push(row);
        if row.1.is_empty() || chain.len() > MODEL_DEFS.len() {
            break;
        }
        cur = row.1;
    }
    let mut set: Vec<&str> = Vec::new();
    for row in chain.iter().rev() {
        for f in row.2 {
            if !set.contains(f) {
                set.push(f);
            }
        }
        for f in row.3 {
            set.retain(|x| *x != *f);
        }
    }
    loop {
        let mut grew = false;
        for (fname, implies, _) in FEATURE_DEFS {
            if set.contains(fname) {
                for i in *implies {
                    if !set.contains(i) {
                        set.push(i);
                        grew = true;
                    }
                }
            }
        }
        if !grew {
            break;
        }
    }
    FEAT_BITS
        .iter()
        .filter(|(n, _)| set.contains(n))
        .fold(0u128, |a, (_, b)| a | b)
}
",
    );
    s
}

/// 既定 CPU モデル（MODEL_DEFS の先頭）の機能を `implies` で閉包し、
/// `FEAT_*` のビット和にしたもの。`--cpu` を省略したときの値。
fn default_feats(model: &Model) -> u128 {
    let Some(first) = model.models.first() else {
        return 0;
    };
    let mut set: std::collections::BTreeSet<&str> = std::collections::BTreeSet::new();
    let mut cur = first;
    let mut chain = Vec::new();
    loop {
        chain.push(cur);
        if cur.parent.is_empty() || chain.len() > model.models.len() {
            break;
        }
        cur = model
            .models
            .iter()
            .find(|m| m.name == cur.parent)
            .expect("model parent");
    }
    for row in chain.iter().rev() {
        set.extend(row.add_features.iter().map(String::as_str));
        for f in &row.remove_features {
            set.remove(f.as_str());
        }
    }
    // implies の閉包。
    loop {
        let mut grew = false;
        for f in &model.features {
            if set.contains(f.name.as_str()) {
                for i in &f.implies {
                    grew |= set.insert(i.as_str());
                }
            }
        }
        if !grew {
            break;
        }
    }
    let extra = match extra_flags(model) {
        Ok(e) => e,
        Err(_) => return 0,
    };
    set.iter()
        .filter_map(|f| extra.iter().position(|e| e == f))
        .fold(0u128, |acc, i| acc | (1u128 << i))
}

/// 命令名を型の識別子にする。`_` で区切り、各語の先頭を大文字にする。
fn to_ident(name: &str) -> String {
    name.split('_')
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                None => String::new(),
                Some(h) => h.to_ascii_uppercase().to_string() + c.as_str(),
            }
        })
        .collect()
}

/// 命令名を関数の識別子にする。英数字は小文字化し、それ以外は `_` に変える。
fn to_snake(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

