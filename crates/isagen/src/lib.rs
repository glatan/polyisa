//! ISADL からのコード生成。検査済みモデルを受け、Rust の源を文字列で返す。
//!
//! 詳しくは [ISA 記述言語](../../../docs/design/isa-description.md) の「生成物」を見る。
//! この骨格は線形のデコーダと単純な逆アセンブラを生成する。
//! 決定木への最適化と `build.rs` への組み込みは後の段階で足す。

#![forbid(unsafe_code)]

pub use polyisa_isadl::Model;

/// 生成に失敗した理由。
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum GenError {
    Invalid(Vec<polyisa_isadl::ValidationError>),
    /// デコーダが評価できない `when` の機能旗。64 個を超える旗で
    /// 符号化を区別しようとしたときに使う。
    UnsupportedWhen(String),
}

impl core::fmt::Display for GenError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Invalid(es) => write!(f, "invalid model ({} errors)", es.len()),
            Self::UnsupportedWhen(name) => write!(f, "unsupported when flag: {name}"),
        }
    }
}

/// 検査して生成する。検査の違反があれば生成しない。
pub fn generate(model: &Model) -> Result<Generated, GenError> {
    let report = polyisa_isadl::validate(model);
    if !report.errors.is_empty() {
        return Err(GenError::Invalid(report.errors));
    }
    Ok(Generated {
        insn_type: gen_insn_type(model),
        decoder: gen_decoder(model)?,
        disassembler: gen_disassembler(model),
        encoder: gen_encoder(model),
        operands: gen_operands(model),
        metadata: gen_metadata(model),
    })
}

/// 生成物の束。
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Generated {
    pub insn_type: String,
    pub decoder: String,
    pub disassembler: String,
    pub encoder: String,
    pub operands: String,
    pub metadata: String,
}

fn gen_insn_type(model: &Model) -> String {
    let mut s = String::from("// generated by isagen. do not edit.\n");
    s.push_str("#[derive(Clone, Copy, PartialEq, Eq, Debug)]\n");
    s.push_str("pub enum Insn {\n");
    for insn in &model.insns {
        s.push_str(&format!("    {},\n", to_ident(&insn.name)));
    }
    s.push_str("}\n");
    s
}

fn gen_decoder(model: &Model) -> Result<String, GenError> {
    let mut s = String::from("// generated by isagen: linear decoder.\n");
    s.push_str("pub fn decode(word: u128, len: u32) -> Option<Insn> {\n");
    s.push_str("    decode_model(word, len, true)\n");
    s.push_str("}\n");
    // モデル対応デコード（ADR-0006）。`when` の述語を評価し、符号化の
    // 重なりを機能で解決する。XLEN（rv32/rv64）は `is_rv64` で受け、
    // それ以外の機能旗は `feats` のビット集合で受ける。
    // `decode` と `decode_model` は既定（RV64、機能なし）を選ぶ互換用の殻である。
    s.push_str("pub fn decode_model(word: u128, len: u32, is_rv64: bool) -> Option<Insn> {\n");
    s.push_str("    decode_model_ex(word, len, is_rv64, 0)\n");
    s.push_str("}\n");
    let extra = extra_flags(model)?;
    for (i, name) in extra.iter().enumerate() {
        s.push_str(&format!(
            "pub const {}: u64 = 1 << {};\n",
            feat_const(name),
            i
        ));
    }
    s.push_str(
        "pub fn decode_model_ex(word: u128, len: u32, is_rv64: bool, feats: u64) -> Option<Insn> {\n",
    );
    // `when` を使わないモデルでは `is_rv64` と `feats` が未使用になる。
    // 呼び出し側の互換性のため引数は残し、警告が出ないよう明示的に破棄する。
    // ビット番号は辞書順で決まるため、新しい旗の追加でずれる。
    // 呼び出し側は数値を直書きせず、生成した `FEAT_*` 定数を使うこと。
    let uses_is_rv64 = model.insns.iter().any(|i| {
        when_guard(&i.when, &extra)
            .unwrap_or_default()
            .contains("is_rv64")
    });
    if !uses_is_rv64 {
        s.push_str("    let _ = is_rv64;\n");
    }
    if extra.is_empty() {
        s.push_str("    let _ = feats;\n");
    }
    s.push_str("    match len {\n");
    // 長さごとに分岐する。RISC-V C拡張の16ビット命令と32ビット命令の混在を想定する。
    let mut lens: Vec<u32> = model.insns.iter().map(|i| i.pattern.len()).collect();
    lens.sort_unstable();
    lens.dedup();
    for l in lens {
        s.push_str(&format!("        {l} => {{\n"));
        for insn in model.insns.iter().filter(|i| i.pattern.len() == l) {
            let guard = when_guard(&insn.when, &extra)?;
            let check = if guard.is_empty() {
                format!(
                    "word & {:#x} == {:#x}",
                    insn.pattern.mask(),
                    insn.pattern.bits()
                )
            } else {
                format!(
                    "word & {:#x} == {:#x} && ({guard})",
                    insn.pattern.mask(),
                    insn.pattern.bits()
                )
            };
            s.push_str(&format!(
                "            // {} (mask {:#x}, bits {:#x})\n",
                insn.name,
                insn.pattern.mask(),
                insn.pattern.bits()
            ));
            if insn.wheres.is_empty() {
                s.push_str(&format!(
                    "            if {check} {{\n                return Some(Insn::{});\n            }}\n",
                    to_ident(&insn.name)
                ));
                continue;
            }
            // `where` 付き：一致後にフィールド値を取り出して条件を評価する。
            s.push_str(&format!("            if {check} {{\n"));
            let tag = to_snake(&insn.name);
            let mut conds = Vec::new();
            for (k, w) in insn.wheres.iter().enumerate() {
                let (hi, lo) = match model.fields.iter().find(|f| f.name == w.field) {
                    Some(f) => match f.kind {
                        polyisa_isadl::model::FieldKind::Bits { hi, lo } => (hi, lo),
                        _ => (0, 0),
                    },
                    None => (0, 0),
                };
                let width = hi - lo + 1;
                let mask: u128 = if width >= 128 {
                    u128::MAX
                } else {
                    (1u128 << width) - 1
                };
                if lo == 0 {
                    s.push_str(&format!(
                        "                let w_{tag}_{k} = word & {mask:#x};\n"
                    ));
                } else {
                    s.push_str(&format!(
                        "                let w_{tag}_{k} = (word >> {lo}) & {mask:#x};\n"
                    ));
                }
                let op = match w.op {
                    polyisa_isadl::model::WhereOp::Eq => "==",
                    polyisa_isadl::model::WhereOp::Ne => "!=",
                };
                conds.push(format!("w_{tag}_{k} {op} {:#x}", w.value));
            }
            s.push_str(&format!(
                "                if {} {{\n                    return Some(Insn::{});\n                }}\n            }}\n",
                conds.join(" && "),
                to_ident(&insn.name)
            ));
        }
        s.push_str("            None\n        }\n");
    }
    s.push_str("        _ => None,\n    }\n}\n");
    Ok(s)
}

/// `when` 述語をデコーダ入口の引数に対する Rust 式にする。
/// 空文字は無条件（`Pred::True`）を表す。XLEN（rv32/rv64）は `is_rv64`
/// で受け、それ以外の機能旗は `feats` のビット集合で受ける。
/// ビットの割り当ては `extra_flags` が決める。
fn when_guard(pred: &polyisa_isadl::pred::Pred, extra: &[String]) -> Result<String, GenError> {
    use polyisa_isadl::pred::Pred;
    match pred {
        Pred::True => Ok(String::new()),
        Pred::False => Ok("false".to_string()),
        Pred::Flag(name) if name == "rv64" => Ok("is_rv64".to_string()),
        Pred::Flag(name) if name == "rv32" => Ok("!is_rv64".to_string()),
        // 呼び出し側が括弧で囲むため、ここでは付けない。
        Pred::Flag(name) if extra.iter().any(|f| f == name) => {
            Ok(format!("feats & {} != 0", feat_const(name)))
        }
        Pred::Flag(name) => Err(GenError::UnsupportedWhen(name.clone())),
        Pred::Not(inner) => Ok(format!("!({})", when_guard(inner, extra)?)),
        Pred::All(ps) => {
            let mut parts = Vec::new();
            for p in ps {
                parts.push(format!("({})", when_guard(p, extra)?));
            }
            Ok(parts.join(" && "))
        }
        Pred::Any(ps) => {
            let mut parts = Vec::new();
            for p in ps {
                parts.push(format!("({})", when_guard(p, extra)?));
            }
            Ok(parts.join(" || "))
        }
    }
}

/// `when` に現れる XLEN 以外の機能旗を集める。辞書順に並べ、位置が
/// ビット番号になる。64 個を超えたら生成しない。
fn extra_flags(model: &Model) -> Result<Vec<String>, GenError> {
    use polyisa_isadl::pred::Pred;
    fn collect(pred: &Pred, out: &mut Vec<String>) {
        match pred {
            Pred::True | Pred::False => {}
            Pred::Flag(name) => {
                if name != "rv32" && name != "rv64" && !out.iter().any(|f| f == name) {
                    out.push(name.clone());
                }
            }
            Pred::Not(inner) => collect(inner, out),
            Pred::All(ps) | Pred::Any(ps) => {
                for p in ps {
                    collect(p, out);
                }
            }
        }
    }
    let mut out = Vec::new();
    for insn in &model.insns {
        collect(&insn.when, &mut out);
    }
    out.sort();
    {
        use std::collections::BTreeSet;
        let mut seen = BTreeSet::new();
        for f in &out {
            if !seen.insert(feat_const(f)) {
                return Err(GenError::UnsupportedWhen(format!(
                    "conflicting feature flag names for {f}"
                )));
            }
        }
    }
    if out.len() > 64 {
        return Err(GenError::UnsupportedWhen(format!(
            "too many feature flags: {}",
            out.len()
        )));
    }
    Ok(out)
}

/// 機能旗の名前を生成コードの定数名にする。
fn feat_const(name: &str) -> String {
    let mut s = String::from("FEAT_");
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            s.push(c.to_ascii_uppercase());
        } else {
            s.push('_');
        }
    }
    s
}

fn gen_disassembler(model: &Model) -> String {
    let mut s = String::from("// generated by isagen: disassembler.\n");
    s.push_str("pub fn disasm(insn: Insn) -> &'static str {\n    match insn {\n");
    for insn in &model.insns {
        s.push_str(&format!(
            "        Insn::{} => {:?},\n",
            to_ident(&insn.name),
            insn.syntax
        ));
    }
    s.push_str("    }\n}\n");
    s
}

fn gen_encoder(model: &Model) -> String {
    let mut s = String::from("// generated by isagen: encoder.\n");
    for insn in &model.insns {
        s.push_str(&format!(
            "pub fn encode_{}(ops: &[u64]) -> Option<u128> {{ let _ = ops; None }}\n",
            to_snake(&insn.name)
        ));
    }
    s.push_str("// TODO: field reverse mapping\n");
    s
}

fn gen_operands(model: &Model) -> String {
    use std::collections::BTreeMap;
    let mut s = String::from(
        "// generated by isagen: operands. 32ビット長の形式だけを扱う。\n// 圧縮形式の取り出しは形式の追加後に生成する。\n",
    );
    let fields: BTreeMap<&str, (u32, u32)> = model
        .fields
        .iter()
        .filter_map(|f| match f.kind {
            polyisa_isadl::model::FieldKind::Bits { hi, lo } => Some((f.name.as_str(), (hi, lo))),
            _ => None,
        })
        .collect();
    for fmt in &model.formats {
        let mut items = Vec::new();
        for fname in &fmt.fields {
            if let Some((hi, lo)) = fields.get(fname.as_str()) {
                items.push((fname.clone(), *hi, *lo));
            }
        }
        if items.is_empty() {
            continue;
        }
        let ty = format!("Ops{}", to_ident(&fmt.name));
        let f = format!("ops_{}", to_snake(&fmt.name));
        s.push_str(&format!("pub struct {ty} {{ pub raw: u128,"));
        for (name, _, _) in &items {
            s.push_str(&format!(" pub {name}: u32,"));
        }
        s.push_str(" }\n");
        s.push_str(&format!("pub fn {f}(word: u128) -> {ty} {{\n"));
        for (name, hi, lo) in &items {
            let width = hi - lo + 1;
            let mask: u128 = if width >= 128 {
                u128::MAX
            } else {
                (1u128 << width) - 1
            };
            if *lo == 0 {
                s.push_str(&format!("    let {name} = (word & {mask:#x}) as u32;\n"));
            } else {
                s.push_str(&format!(
                    "    let {name} = ((word >> {lo}) & {mask:#x}) as u32;\n"
                ));
            }
        }
        s.push_str(&format!("    {ty} {{ raw: word,"));
        for (name, _, _) in &items {
            s.push_str(&format!(" {name},"));
        }
        s.push_str(" }\n}\n");
    }
    s
}

fn gen_metadata(model: &Model) -> String {
    let mut s = String::from("// generated by isagen: metadata.\n");
    s.push_str("pub struct InsnMeta { pub name: &'static str, pub timing: &'static str }\n");
    s.push_str("pub const INSNS: &[InsnMeta] = &[\n");
    for insn in &model.insns {
        s.push_str(&format!(
            "    InsnMeta {{ name: {:?}, timing: {:?} }},\n",
            insn.name, insn.timing
        ));
    }
    s.push_str("];\n");
    s.push_str("pub const FEATURES: &[&str] = &[\n");
    for f in &model.features {
        s.push_str(&format!("    {:?},\n", f.name));
    }
    s.push_str("];\n");
    s.push_str("pub const MODELS: &[&str] = &[\n");
    for m in &model.models {
        s.push_str(&format!("    {:?},\n", m.name));
    }
    s.push_str("];\n");
    s
}

/// 命令名を型の識別子にする。`_` で区切り、各語の先頭を大文字にする。
fn to_ident(name: &str) -> String {
    name.split('_')
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                None => String::new(),
                Some(h) => h.to_ascii_uppercase().to_string() + c.as_str(),
            }
        })
        .collect()
}

/// 命令名を関数の識別子にする。英数字は小文字化し、それ以外は `_` に変える。
fn to_snake(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use polyisa_isadl::model::*;
    use polyisa_isadl::pattern::Pattern;
    use polyisa_isadl::pred::Pred;

    fn model() -> Model {
        let mut m = Model::new();
        m.timing_classes.push("alu".to_string());
        m.formats.push(Format {
            name: "R".to_string(),
            fields: vec![],
            operands: vec![],
        });
        m.insns.push(Insn {
            name: "add".to_string(),
            format: "R".to_string(),
            pattern: Pattern::parse("0000000 ..... ..... 000 ..... 0110011").unwrap(),
            when: Pred::True,
            wheres: vec![],
            syntax: "add {rd}, {rs1}, {rs2}".to_string(),
            timing: "alu".to_string(),
        });
        m
    }

    #[test]
    fn generates_all_parts() {
        let g = generate(&model()).unwrap();
        assert!(g.insn_type.contains("Add"));
        assert!(g.disassembler.contains("add {rd}"));
        assert!(g.metadata.contains("alu"));
        assert!(g.metadata.contains("FEATURES"));
        assert!(g.metadata.contains("MODELS"));
        assert!(g.encoder.contains("encode_add"));
    }

    #[test]
    fn decoder_emits_mask_compare() {
        // ADD: funct7=0000000、funct3=000、opcode=0110011。
        let g = generate(&model()).unwrap();
        assert!(g.decoder.contains("0xfe00707f"));
        assert!(g.decoder.contains("0x33"));
        assert!(g.decoder.contains("Some(Insn::Add)"));
    }

    #[test]
    fn decoder_supports_mixed_lengths() {
        let mut m = model();
        m.insns.push(Insn {
            name: "c_addi".to_string(),
            format: "R".to_string(),
            pattern: Pattern::parse("000. ..... ..... 01").unwrap(),
            when: Pred::True,
            wheres: vec![],
            syntax: "c.addi".to_string(),
            timing: "alu".to_string(),
        });
        let g = generate(&m).unwrap();
        assert!(g.decoder.contains("32 =>"));
        assert!(g.decoder.contains("16 =>"));
        assert!(g.decoder.contains("Some(Insn::CAddi)"));
    }

    #[test]
    fn decoder_evaluates_where_clauses() {
        use polyisa_isadl::model::{FieldKind, WhereClause, WhereOp};
        let mut m = model();
        for (name, hi, lo) in [("rd", 11, 7), ("rs1", 19, 15), ("rs2", 24, 20)] {
            m.fields.push(Field {
                name: name.to_string(),
                kind: FieldKind::Bits { hi, lo },
            });
        }
        m.formats[0].fields = vec!["rd".to_string(), "rs1".to_string()];
        m.insns[0].wheres = vec![WhereClause {
            field: "rs2".to_string(),
            op: WhereOp::Eq,
            value: 0,
        }];
        let g = generate(&m).unwrap();
        assert!(g.decoder.contains("w_add_0 == 0x0"));
        assert!(g.decoder.contains("Some(Insn::Add)"));
    }

    #[test]
    fn decoder_guards_when_with_xlen() {
        let mut m = model();
        m.insns.push(Insn {
            name: "c_jal".to_string(),
            format: "R".to_string(),
            pattern: Pattern::parse("001 ..... ..... 01").unwrap(),
            when: Pred::Not(Box::new(Pred::Flag("rv64".to_string()))),
            wheres: vec![],
            syntax: "c.jal".to_string(),
            timing: "alu".to_string(),
        });
        let g = generate(&m).unwrap();
        // モデル対応入口があり、`when` が `is_rv64` の式になる。
        assert!(
            g.decoder
                .contains("fn decode_model(word: u128, len: u32, is_rv64: bool)")
        );
        assert!(g.decoder.contains("!(is_rv64)"));
        assert!(g.decoder.contains("Some(Insn::CJal)"));
    }

    #[test]
    fn decoder_accepts_feature_flag_with_feats() {
        // XLEN 以外の旗は `feats` のビット集合で受ける。
        let mut m = model();
        m.insns[0].when = Pred::Flag("m".to_string());
        let g = generate(&m).unwrap();
        assert!(g.decoder.contains("pub const FEAT_M: u64 = 1 << 0;"));
        assert!(g.decoder.contains("(feats & FEAT_M != 0)"));
        // 旗だけのモデルでは `is_rv64` が未使用になる。
        assert!(g.decoder.contains("let _ = is_rv64;"));
        assert!(!g.decoder.contains("let _ = feats;"));
        assert!(
            g.decoder
                .contains("fn decode_model_ex(word: u128, len: u32, is_rv64: bool, feats: u64)")
        );
        // 互換用の入口は既定（機能なし）で拡張版に委譲する。
        assert!(g.decoder.contains("decode_model_ex(word, len, is_rv64, 0)"));
    }

    #[test]
    fn decoder_guards_overlapping_encodings_with_feature() {
        // 同じ符号化を `when` の肯定と否定で振り分ける（R6 の割り当て直しの形）。
        let mut m = model();
        m.insns[0].when = Pred::Not(Box::new(Pred::Flag("mips_r6".to_string())));
        m.insns.push(Insn {
            name: "bovc_like".to_string(),
            format: "R".to_string(),
            pattern: Pattern::parse("0000000 ..... ..... 000 ..... 0110011").unwrap(),
            when: Pred::Flag("mips_r6".to_string()),
            wheres: vec![],
            syntax: "bovc_like".to_string(),
            timing: "alu".to_string(),
        });
        let g = generate(&m).unwrap();
        assert!(g.decoder.contains("pub const FEAT_MIPS_R6: u64 = 1 << 0;"));
        assert!(g.decoder.contains("(!(feats & FEAT_MIPS_R6 != 0))"));
        assert!(g.decoder.contains("(feats & FEAT_MIPS_R6 != 0)"));
    }

    #[test]
    fn decoder_rejects_too_many_feature_flags() {
        let mut m = model();
        for i in 0..65u32 {
            m.insns.push(Insn {
                name: format!("f{i}"),
                format: "R".to_string(),
                pattern: Pattern::parse(&format!("0{:07b}", i)).unwrap(),
                when: Pred::Flag(format!("feat{i}")),
                wheres: vec![],
                syntax: format!("f{i}"),
                timing: "alu".to_string(),
            });
        }
        assert!(matches!(generate(&m), Err(GenError::UnsupportedWhen(_))));
    }

    #[test]
    fn operands_extracts_declared_fields() {
        use polyisa_isadl::model::FieldKind;
        let mut m = model();
        m.fields.push(Field {
            name: "rd".to_string(),
            kind: FieldKind::Bits { hi: 11, lo: 7 },
        });
        m.fields.push(Field {
            name: "rs1".to_string(),
            kind: FieldKind::Bits { hi: 19, lo: 15 },
        });
        m.formats[0].fields = vec!["rd".to_string(), "rs1".to_string()];
        let g = generate(&m).unwrap();
        assert!(g.operands.contains("pub struct OpsR"));
        assert!(g.operands.contains("pub fn ops_r"));
        assert!(g.operands.contains(">> 7"));
        assert!(g.operands.contains(">> 15"));
    }

    #[test]
    fn ident_is_camel_case() {
        assert_eq!(to_ident("add"), "Add");
        assert_eq!(to_ident("fence_i"), "FenceI");
        assert_eq!(to_snake("fence_i"), "fence_i");
    }

    #[test]
    fn invalid_model_fails() {
        let mut m = model();
        m.insns.push(Insn {
            name: "add2".to_string(),
            format: "R".to_string(),
            pattern: Pattern::parse("0000000 ..... ..... 000 ..... 0110011").unwrap(),
            when: Pred::True,
            wheres: vec![],
            syntax: "add".to_string(),
            timing: "alu".to_string(),
        });
        assert!(generate(&m).is_err());
    }
}
