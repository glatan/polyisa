//! m68k ABI 表とカーネル UAPI の突き合わせ（層6・abi、S14-E3）。
//!
//! m68k の UAPI 番号は `arch/m68k/kernel/syscalls/syscall.tbl` が
//! 正本で、abi 列は全行 `common`。先頭 `_` の名前（`_llseek`・
//! `_newselect`・`_sysctl`）はこちら側の定数名では `_` を落として
//! 大文字化する。
//! 出典は `.testdata/uapi-m68k`（台帳 SRC-LINUX-M68K-UAPI・用途T）。
//! データがなければ devtool test:plan が外す。

use std::path::PathBuf;

fn data_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../.testdata/uapi-m68k")
}

/// `syscall.tbl` の全行を name→番号に畳む。
fn tbl_numbers(path: &PathBuf) -> std::collections::HashMap<String, u64> {
    let text = std::fs::read_to_string(path).expect("syscall.tbl を読む");
    let mut map = std::collections::HashMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut cols = line.split_whitespace();
        let (num, name) = match (cols.next(), cols.next(), cols.next()) {
            (Some(n), Some(_abi), Some(nm)) => (n, nm),
            _ => panic!("tbl の行が読めない: {line:?}"),
        };
        let n: u64 = num
            .parse()
            .unwrap_or_else(|_| panic!("tbl の番号: {line:?}"));
        map.insert(name.to_string(), n);
    }
    map
}

