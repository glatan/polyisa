/// 逆方向: UAPI の全番号について `m68k::name` が同じ名前を返す。
#[test]
fn name_table_covers_uapi_m68k() {
    let tbl = data_dir().join("syscall.tbl");
    assert!(
        tbl.is_file(),
        "SRC-LINUX-M68K-UAPI を {} に置く。リポジトリには含めない。",
        data_dir().display()
    );
    let nums = tbl_numbers(&tbl);
    for (name, nr) in &nums {
        // name() は UAPI の名前を `_` 込みで保持する（`_llseek` 等）。
        let got = polyisa_os_linux::m68k::name(*nr);
        assert_eq!(
            got,
            Some(name.as_str()),
            "__NR_{name}({nr}) の名前一貫性が UAPI と食い違う"
        );
    }
}
